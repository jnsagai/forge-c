/**
  @file    stm32n6xx_ll_crc.h
  @brief   STM32N6 CRC independent data register (IDR) LL driver, header-only.

  @details QM development candidate (WO-F014-QWEN-CRC-IDR-DELIVERY-20261030-01).
           Exposes only the two scoped public functions for the general-purpose
           32-bit independent data register:
             - LL_CRC_Write_IDR(CRC_TypeDef *CRCx, uint32_t InData)
             - LL_CRC_Read_IDR(const CRC_TypeDef *CRCx)

           Hardware authority: RM0486 Rev 4 section 26.4.2 (CRC_IDR), p.1172:
             - Address offset 0x04, reset value 0x00000000
             - Bits 31:0 IDR[31:0]: general-purpose 32-bit data register bits,
               all read/write (rw); usable as temporary storage for four bytes
             - Not affected by CRC resets generated by RESET bit in CRC_CR
           CRC register layout and instance base are taken from the immutable,
           source-backed fixture forge_crc_device.h (derived from ST
           cmsis-device-n6 v1.4.0 stm32n657xx.h CRC_TypeDef; CRC secure base
           0x56024C00, RM0486 p.176). This header does not redeclare
           CRC_TypeDef and does not define any singleton register object.

  @preconditions (caller-owned, not checked here; invalid pointers or
           inaccessible hardware are outside the supported invocation domain):
             - CRCx points to a valid, accessible CRC instance
             - Caller owns clock, power, security and bus access setup
           No startup accesses, status polling, allocation or setup occur in
           this scope. CRC polynomial/calculation/configuration is out of scope.
*/
#ifndef STM32N6XX_LL_CRC_H
#define STM32N6XX_LL_CRC_H

#include "forge_crc_device.h"

/* Exported functions ------------------------------------------------------- */

/**
  @brief  Write the supplied 32-bit value to CRC_IDR.IDR[31:0].
  @param  CRCx   CRC instance handle (valid, accessible; caller precondition)
  @param  InData 32-bit value written, all 32 bits (RM0486 p.1172)
  @retval None
  @note   Single aligned 32-bit volatile write; no other register or peripheral
          instance is read, written or otherwise modified.
*/
static void LL_CRC_Write_IDR(CRC_TypeDef *CRCx, uint32_t InData)
{
    CRCx->IDR = InData;
}

/**
  @brief  Read the 32-bit value stored in CRC_IDR.IDR[31:0].
  @param  CRCx CRC instance handle (valid, accessible; caller precondition)
  @retval The 32-bit value currently held in the independent data register
  @note   Single aligned 32-bit volatile read; no register is written and no
          CRC calculation is triggered or modified.
*/
static uint32_t LL_CRC_Read_IDR(const CRC_TypeDef *CRCx)
{
    return CRCx->IDR;
}

#endif /* STM32N6XX_LL_CRC_H */
