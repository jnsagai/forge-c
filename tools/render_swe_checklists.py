def data() -> list[dict]:
    out = []
    for p in PHASES:
        cl = load_checklist(p)
        out.append({"phase": p, "name": NAMES[p], "version": cl["version"], "sha": cl["sha256"][:12],
                    "max_rework": cl["policy"].get("maximum_rework_cycles"),
                    "checks": [{"id": c["id"], "required": bool(c.get("required")), "sev": c.get("severity_if_failed"),
                                "criterion": " ".join(str(c["criterion"]).split()),
                                "by": DET.get(c.get("deterministic_check") or "", "")} for c in cl["checks"]],
                    "outputs": REQUIRED_OUTPUTS.get(p, []),
                    "tools": [f"{o} PASS" for _, o in REQUIRED_TOOL_PASS.get(p, [])], "extra": GATE_EXTRA[p]})
    return out


def markdown(d: list[dict]) -> str:
    L = ["# SWE.1–SWE.6 validation requirements (generated)", "",
         "Generated by `tools/render_swe_checklists.py` from the hash-pinned v0.4 checklists (v0.3 base + additive "
         "overlay), the author-gate presence rules and the v0.5 release policy. Deterministic items are decided by "
         "tools and override the inspector's verdict; all other items are judged by an independent inspector agent.", ""]
    for p in d:
        L += [f"## {p['phase']} — {p['name']}", "", f"Checklist v{p['version']} (sha256 {p['sha']}…), rework budget "
              f"{p['max_rework']} (the factory blocks after 2 failed cycles, ADR-0005).", "",
              "**Before freeze (author gate):** " + "; ".join([f"`{o}`" for o in p["outputs"]] + p["tools"]) + ".", ""]
        L += [f"- {x}" for x in p["extra"]] + ([""] if p["extra"] else [])
        L += ["| ID | Required | If failed | Criterion | Decided by |", "|---|---|---|---|---|"]
        L += [f"| {c['id']} | {'yes' if c['required'] else 'no'} | {c['sev']} | {c['criterion']} | "
              f"{c['by'] or 'Inspector'} |" for c in p["checks"]] + [""]
    L += ["## Release package (READY_FOR_OFFLINE_REVIEW requires all)", "", "| Check | Rule |", "|---|---|"]
    L += [f"| {k} | {v} |" for k, v in RELEASE] + [""]
    return "\n".join(L)


