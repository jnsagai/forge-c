"""AFO M2 (T020-T022; AFO-FR-013/015/020/021/024/025) - deterministic, model-free scheduler cycle.

One cycle: take the scheduler lease (fencing epoch), pick the next QUEUED order (FIFO + priority aging, honouring
backoff), and decide by mode:
  DISABLED      nothing;
  OBSERVE_ONLY  record what it would do (simulated decision), change nothing;
  PILOT/ACTIVE  authority check (signed authorization covers this order/driver/model) -> admission preflight
                (mounted data volume, Fabro + gateway health, allowed model, MCP registry, attempt budget) -> admit
                (QUEUED->ADMITTED + FABRO_LAUNCH outbox intent, atomically, under the epoch) or defer with bounded
                exponential backoff when a dependency is down.
No order is ever generated here (allow_autogenerated_work_orders is false by policy), and the cycle makes no model
call. Every outcome is a decision record.
"""

from __future__ import annotations

import json
import os
import urllib.request
from pathlib import Path

from ..common import REPO_ROOT
from . import authority, host
from .policy import load, record
from .queue import QueueError, Store

SCOPE = "scheduler"


def _healthy(url: str, timeout: float = 3.0) -> bool:
    try:
        with urllib.request.urlopen(url, timeout=timeout) as r:  # noqa: S310 - loopback health URL from config
            return 200 <= r.status < 300
    except OSError:
        return False


def launch_manifest(order: dict, repo: Path = REPO_ROOT) -> dict:
    return json.loads((repo / order["input_manifest_ref"]).read_text())


def preflight(order: dict, eff, store: Store, probes: dict | None = None) -> list[str]:
    """Admission guards; `probes` overrides the live checks (tests)."""
    p = probes or {}
    issues = []
    from .dispatch import _durable_order

    durable = _durable_order(store, order["order_id"])

    def available(name, condition, observe):
        if not durable:
            return observe()
        from .dependency_wait import probe

        observed = probe(store, "admission:" + name, condition, lambda: {"ok": bool(observe())})
        return observed.get("healthy") is True

    from . import qualification_intake
    from .durable import Refused

    try:
        intake = qualification_intake.context(store, order)
        frozen = qualification_intake.launch_manifest(intake) if intake else None
    except Refused:
        return ["QUALIFICATION_INTAKE_BINDING_CHANGED"]

    def manifest_for():
        return frozen if intake else launch_manifest(order)

    env = json.loads(order["envelope"])
    if not p.get("mount", lambda: host.preflight()["ok"])():
        issues.append("DATA_VOLUME_NOT_READY")
    from .housekeeping import capacity
    from ..common import data_root

    if not p.get("capacity", lambda: capacity(data_root())["ok"])():
        issues.append("CONTROL_PLANE_STORAGE_RESERVE_LOW")
    fabro_url = os.environ.get("FORGE_FABRO_URL", "http://127.0.0.1:32291/api/v1").rstrip("/")
    if not available("fabro", fabro_url, p.get("fabro", lambda: _healthy(fabro_url.rsplit("/api", 1)[0] + "/health"))):
        issues.append("FABRO_UNAVAILABLE")
    if not available("gateway", env["model_profile"], p.get("gateway", lambda: _healthy(gateway_health_url(order, frozen)))):
        issues.append("MODEL_GATEWAY_UNAVAILABLE")
    if env["model_profile"] not in (eff.get("engineering.allowed_model_profiles") or []):
        issues.append(f"MODEL_NOT_ALLOWED:{env['model_profile']}")
    if not p.get("mcp", _mcp_ok)():
        issues.append("MCP_REGISTRY_INVALID")
    if os.environ.get("FORGE_DURABLE_AUTONOMY") == "1" or intake:
        from .mission_ledger import MissionLedger

        try:
            mission = MissionLedger(store).for_order(order["order_id"])
            snap = MissionLedger(store).snapshot(mission)
            limits = snap["limits"]
            import time

            if intake and (mission != intake["mission_id"] or limits["max_attempts"] != 0 or snap["attempts"]):
                issues.append("QUALIFICATION_MISSION_NOT_PROTOCOL_ONLY")
            elif intake:
                # A protocol-only mission spends finite jobs/requests/tokens, never product attempts.
                if (
                    time.time() >= limits["deadline"]
                    or snap["jobs"] >= limits["max_jobs"]
                    or snap["requests"] >= limits["max_requests"]
                    or snap["charged_tokens"] + intake["job_token_reservation"] > limits["max_tokens"]
                ):
                    issues.append("MISSION_ALLOWANCE_EXHAUSTED")
            elif (
                time.time() >= limits["deadline"]
                or snap["attempts"] >= limits["max_attempts"]
                or snap["charged_tokens"] >= limits["max_tokens"]
            ):
                issues.append("MISSION_ALLOWANCE_EXHAUSTED")
            with store.tx() as c:
                held = c.execute("SELECT holder FROM afo_resource_ownership WHERE resource='inference'").fetchone()
            if held and held[0]:
                issues.append("NATIVE_INFERENCE_CAPACITY_HELD")
        except Refused as exc:
            issues.append(exc.code)
    if durable:
        try:
            manifest = p.get("manifest", manifest_for)()
            for parent in manifest.get("depends_on_order_ids", []):

                def ready(parent=parent):
                    dependency = store.order(parent)
                    return bool(dependency and dependency["state"] == "READY_FOR_OFFLINE_REVIEW")

                if not available("order", parent, ready):
                    issues.append("ORDER_DEPENDENCY_NOT_READY:" + parent)
        except (OSError, ValueError, TypeError):
            issues.append("LAUNCH_MANIFEST_UNAVAILABLE_OR_INVALID")
    if len(store.attempts(order["order_id"])) >= int(eff.get("budgets.max_order_attempts", 0)):
        issues.append("ORDER_ATTEMPT_BUDGET_EXHAUSTED")
    if intake:
        try:
            grant = qualification_intake.grant_record(intake["authorization_ref"])
        except (OSError, ValueError):
            grant = {}
        if (
            eff.get("authorization_ref") != intake["authorization_ref"]
            or grant.get("signed_runbook_ref") != intake["qualification_ref"]
        ):
            issues.append("SIGNED_CAMPAIGN_RUNBOOK_MISMATCH")
    return issues


def gateway_health_url(order: dict, manifest: dict | None = None) -> str:
    manifest = launch_manifest(order) if manifest is None else manifest
    if manifest.get("profile"):
        from ..lrtx.profile import load

        port = int(load(manifest["profile"])["deployment"]["ports"]["gateway"])
        return f"http://127.0.0.1:{port}/health"
    return "http://127.0.0.1:11437/health"


def _mcp_ok() -> bool:
    from ..registry.mcp_registry import load_registry

    try:
        load_registry()
        return True
    except Exception:  # noqa: BLE001 - an unreadable registry admits nothing
        return False


def cycle(store: Store, owner: str, *, eff=None, probes: dict | None = None, now: float | None = None) -> dict:
    eff = eff or load()
    out = {"kind": "scheduler_cycle", "mode": eff.mode}
    if eff.mode == "DISABLED":
        return {**out, "action": "none"}
    epoch = store.acquire_lease(SCOPE, owner, float(eff.get("queue.lease_seconds", 120)), now=now)
    if epoch is None:
        return {**out, "action": "lease_held_elsewhere"}
    if eff.mode != "OBSERVE_ONLY":  # AFO-T051: a wait for an external factory change is bounded (order wall budget)
        expired = store.expire_waiting(float(eff.get("budgets.max_order_wall_seconds", 86400)), now=now)
        if expired:
            out["expired_waiting"] = expired
    # WAITING_EXTERNAL_CHANGE holds no capacity (not an ACTIVE state): unrelated approved orders keep being scheduled
    from .operations import configured, Intent

    if configured() and Intent().read()["mode"] != "RUNNING":
        return {**out, "action": "operations_wait"}
    cand = store.next_candidate(float(eff.get("queue.priority_aging_seconds", 3600)), now=now)
    if cand is None:
        return {**out, "action": "idle", "epoch": epoch}
    try:
        env = json.loads(cand["envelope"])
        if not isinstance(env, dict) or any(k not in env for k in ("request_id", "driver_class", "model_profile")):
            raise ValueError("MALFORMED_QUEUE_ENVELOPE")
    except (ValueError, TypeError):
        if eff.mode != "OBSERVE_ONLY":
            store.transition(cand["order_id"], "BLOCKED", "MALFORMED_QUEUE_ITEM", terminal_reason="MALFORMED_QUEUE_ITEM")
        return {**out, "action": "malformed_item_blocked", "order_id": cand["order_id"]}
    request = {"order_id": env["request_id"], "driver_class": env["driver_class"], "model": env["model_profile"]}
    out.update(order_id=cand["order_id"], epoch=epoch)
    if eff.mode == "OBSERVE_ONLY":
        issues = preflight(cand, eff, store, probes)
        rec = {**out, "action": "simulated", "would": "defer" if issues else "admit", "issues": issues}
        record(rec)
        return rec
    d = authority.decide("launch_workorder", request, afo=eff)
    if not d.allow:
        store.defer(cand["order_id"], "AUTHORITY:" + d.code, now=now)
        rec = {**out, "action": "refused", "code": d.code}
        record(rec)
        return rec
    issues = preflight(cand, eff, store, probes)
    if issues:
        if any(
            i in issues
            for i in (
                "ORDER_ATTEMPT_BUDGET_EXHAUSTED",
                "MISSION_ALLOWANCE_EXHAUSTED",
                "MISSION_LINK_REQUIRED",
                "QUALIFICATION_INTAKE_BINDING_CHANGED",
                "QUALIFICATION_MISSION_NOT_PROTOCOL_ONLY",
            )
        ) or any(i.startswith("MODEL_NOT_ALLOWED") for i in issues):
            store.transition(cand["order_id"], "BLOCKED", "; ".join(issues), terminal_reason=issues[0])
            rec = {**out, "action": "blocked", "issues": issues}
        else:
            wait = store.defer(cand["order_id"], "; ".join(issues), now=now)
            rec = {**out, "action": "deferred", "issues": issues, "wait_s": wait}
        record(rec)
        return rec
    from . import qualification_intake

    intake = qualification_intake.context(store, cand)  # verified by preflight in this cycle
    try:
        aid = store.admit(
            cand["order_id"],
            epoch=epoch,
            scope=SCOPE,
            policy_sha256=eff.sha256,
            authorization_id=eff.authorization_id,
            max_concurrent=int(eff.get("queue.max_concurrent_workorders", 1)),
            qualification_ref=intake["qualification_ref"] if intake else None,
        )
    except QueueError as e:
        rec = {**out, "action": "not_admitted", "code": e.code}
    else:
        rec = {**out, "action": "admitted", "attempt_id": aid}
    record(rec)
    return rec
