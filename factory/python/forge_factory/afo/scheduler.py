"""AFO M2 (T020-T022; AFO-FR-013/015/020/021/024/025) - deterministic, model-free scheduler cycle.

One cycle: take the scheduler lease (fencing epoch), pick the next QUEUED order (FIFO + priority aging, honouring
backoff), and decide by mode:
  DISABLED      nothing;
  OBSERVE_ONLY  record what it would do (simulated decision), change nothing;
  PILOT/ACTIVE  authority check (signed authorization covers this order/driver/model) -> admission preflight
                (mounted data volume, Fabro + gateway health, allowed model, MCP registry, attempt budget) -> admit
                (QUEUED->ADMITTED + FABRO_LAUNCH outbox intent, atomically, under the epoch) or defer with bounded
                exponential backoff when a dependency is down.
No order is ever generated here (allow_autogenerated_work_orders is false by policy), and the cycle makes no model
call. Every outcome is a decision record.
"""
from __future__ import annotations

import json
import os
import urllib.request
from pathlib import Path

from ..common import REPO_ROOT
from . import authority, host
from .policy import load, record
from .queue import QueueError, Store

SCOPE = "scheduler"


def _healthy(url: str, timeout: float = 3.0) -> bool:
    try:
        with urllib.request.urlopen(url, timeout=timeout) as r:  # noqa: S310 - loopback health URL from config
            return 200 <= r.status < 300
    except OSError:
        return False


def launch_manifest(order: dict, repo: Path = REPO_ROOT) -> dict:
    return json.loads((repo / order["input_manifest_ref"]).read_text())


def preflight(order: dict, eff, store: Store, probes: dict | None = None) -> list[str]:
    """Admission guards; `probes` overrides the live checks (tests)."""
    p = probes or {}
    issues = []
    env = json.loads(order["envelope"])
    if not p.get("mount", lambda: host.preflight()["ok"])():
        issues.append("DATA_VOLUME_NOT_READY")
    fabro_url = os.environ.get("FORGE_FABRO_URL", "http://127.0.0.1:32291/api/v1").rstrip("/")
    if not p.get("fabro", lambda: _healthy(fabro_url.rsplit("/api", 1)[0] + "/health"))():
        issues.append("FABRO_UNAVAILABLE")
    if not p.get("gateway", lambda: _healthy(gateway_health_url(order)))():
        issues.append("MODEL_GATEWAY_UNAVAILABLE")
    if env["model_profile"] not in (eff.get("engineering.allowed_model_profiles") or []):
        issues.append(f"MODEL_NOT_ALLOWED:{env['model_profile']}")
    if not p.get("mcp", _mcp_ok)():
        issues.append("MCP_REGISTRY_INVALID")
    if len(store.attempts(order["order_id"])) >= int(eff.get("budgets.max_order_attempts", 0)):
        issues.append("ORDER_ATTEMPT_BUDGET_EXHAUSTED")
    return issues


def gateway_health_url(order: dict) -> str:
    manifest = launch_manifest(order)
    if manifest.get("profile"):
        from ..lrtx.profile import load

        port = int(load(manifest["profile"])["deployment"]["ports"]["gateway"])
        return f"http://127.0.0.1:{port}/health"
    return "http://127.0.0.1:11437/health"


def _mcp_ok() -> bool:
    from ..registry.mcp_registry import load_registry

    try:
        load_registry()
        return True
    except Exception:  # noqa: BLE001 - an unreadable registry admits nothing
        return False


def cycle(store: Store, owner: str, *, eff=None, probes: dict | None = None, now: float | None = None) -> dict:
    eff = eff or load()
    out = {"kind": "scheduler_cycle", "mode": eff.mode}
    if eff.mode == "DISABLED":
        return {**out, "action": "none"}
    epoch = store.acquire_lease(SCOPE, owner, float(eff.get("queue.lease_seconds", 120)), now=now)
    if epoch is None:
        return {**out, "action": "lease_held_elsewhere"}
    if eff.mode != "OBSERVE_ONLY":  # AFO-T051: a wait for an external factory change is bounded (order wall budget)
        expired = store.expire_waiting(float(eff.get("budgets.max_order_wall_seconds", 86400)), now=now)
        if expired:
            out["expired_waiting"] = expired
    # WAITING_EXTERNAL_CHANGE holds no capacity (not an ACTIVE state): unrelated approved orders keep being scheduled
    cand = store.next_candidate(float(eff.get("queue.priority_aging_seconds", 3600)), now=now)
    if cand is None:
        return {**out, "action": "idle", "epoch": epoch}
    env = json.loads(cand["envelope"])
    request = {"order_id": env["request_id"], "driver_class": env["driver_class"], "model": env["model_profile"]}
    out.update(order_id=cand["order_id"], epoch=epoch)
    if eff.mode == "OBSERVE_ONLY":
        issues = preflight(cand, eff, store, probes)
        rec = {**out, "action": "simulated", "would": "defer" if issues else "admit", "issues": issues}
        record(rec)
        return rec
    d = authority.decide("launch_workorder", request, afo=eff)
    if not d.allow:
        rec = {**out, "action": "refused", "code": d.code}
        record(rec)
        return rec
    issues = preflight(cand, eff, store, probes)
    if issues:
        if "ORDER_ATTEMPT_BUDGET_EXHAUSTED" in issues or any(i.startswith("MODEL_NOT_ALLOWED") for i in issues):
            store.transition(cand["order_id"], "BLOCKED", "; ".join(issues), terminal_reason=issues[0])
            rec = {**out, "action": "blocked", "issues": issues}
        else:
            wait = store.defer(cand["order_id"], "; ".join(issues), now=now)
            rec = {**out, "action": "deferred", "issues": issues, "wait_s": wait}
        record(rec)
        return rec
    try:
        aid = store.admit(cand["order_id"], epoch=epoch, scope=SCOPE, policy_sha256=eff.sha256,
                          authorization_id=eff.authorization_id,
                          max_concurrent=int(eff.get("queue.max_concurrent_workorders", 1)))
    except QueueError as e:
        rec = {**out, "action": "not_admitted", "code": e.code}
    else:
        rec = {**out, "action": "admitted", "attempt_id": aid}
    record(rec)
    return rec
