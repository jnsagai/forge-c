"""AFO-T004 (AFO-FR-002/003/004/006) - fail-closed AFO policy loader.

* Missing, unreadable or schema-invalid policy -> mode DISABLED (nothing is admitted); the reason is recorded.
* The schema pins every non-weakening invariant (no source auto-deploy, reuse of 002/003/004, MCP-only agents...);
  `floor_violations` re-checks them in code (defence in depth, AT-064) so a schema edit alone cannot open them.
* DISABLED and OBSERVE_ONLY need no authorization. PILOT/ACTIVE take effect only with a valid signed owner
  authorization bound to this policy's sha256 (authz.find); otherwise the effective mode is OBSERVE_ONLY.
* Every evaluation is a deterministic decision record (no model call) appended to <state>/afo/decisions.jsonl.
"""
from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path

from ..common import REPO_ROOT, canonical_json, load_yaml, sha256_bytes, state_dir, utc_now

POLICY_PATH = REPO_ROOT / "config/factory/afo-policy.yaml"
SCHEMA = REPO_ROOT / "specs/005-autonomous-factory-operations/contracts/afo-policy.schema.json"
MODES = ("DISABLED", "OBSERVE_ONLY", "PILOT", "ACTIVE")
# exactly one permitted value each - the constitution/CRE floor AFO can never weaken (AT-064)
FLOOR = {
    "integration.no_auto_source_deploy": True, "integration.reuse_002_supervisor": True,
    "integration.reuse_004_cre": True, "integration.reuse_003_kpi": True, "integration.use_existing_fabro": True,
    "maintenance.auto_merge_source": False, "maintenance.auto_promote_factory_code": False,
    "maintenance.auto_mutate_safety_policy": False, "maintenance.protect_holdouts": True,
    "engineering.preserve_independent_inspector": True, "engineering.require_material_difference": True,
    "security.all_new_agent_calls_mcp_only": True, "security.deny_agent_direct_shell": True,
    "security.redact_secrets": True, "security.unknown_side_effect_fail_closed": True,
    "queue.allow_autogenerated_work_orders": False, "queue.submission_requires_approval": True,
}


@dataclass(frozen=True)
class Effective:
    mode: str
    requested_mode: str | None
    sha256: str | None
    policy: dict | None
    issues: list[str] = field(default_factory=list)
    authorization_id: str | None = None

    def get(self, dotted: str, default=None):
        cur = self.policy or {}
        for part in dotted.split("."):
            if not isinstance(cur, dict) or part not in cur:
                return default
            cur = cur[part]
        return cur


def _get(d: dict, dotted: str):
    cur = d
    for part in dotted.split("."):
        if not isinstance(cur, dict) or part not in cur:
            return KeyError
        cur = cur[part]
    return cur


def floor_violations(pol: dict) -> list[str]:
    return [f"FLOOR_VIOLATION:{k}={_get(pol, k)!r} (must be {v!r})" for k, v in FLOOR.items() if _get(pol, k) != v]


def schema_errors(pol) -> list[str]:
    import jsonschema

    v = jsonschema.Draft202012Validator(json.loads(SCHEMA.read_text()), format_checker=jsonschema.FormatChecker())
    return [f"SCHEMA:{'/'.join(map(str, e.path)) or '<root>'}: {e.message}"[:200] for e in v.iter_errors(pol)]


def record(decision: dict) -> None:
    """Append-only deterministic decision log (AFO-FR-006); failures to log never open anything."""
    try:
        d = state_dir() / "afo"
        d.mkdir(parents=True, exist_ok=True)
        rec = {"ts": utc_now(), **decision}
        rec["decision_id"] = "afo-dec-" + sha256_bytes(canonical_json(rec))[:16]
        with (d / "decisions.jsonl").open("a", encoding="utf-8") as f:
            f.write(json.dumps(rec, sort_keys=True) + "\n")
    except OSError:
        pass


def load(path: Path | None = None, *, auth_base: Path | None = None, now=None, log: bool = False) -> Effective:
    from . import authz

    p = Path(path or POLICY_PATH)
    try:
        pol = load_yaml(p) if p.is_file() else None
    except Exception as exc:  # noqa: BLE001 - unreadable policy is a DISABLED factory, never an exception path
        pol, err = None, f"POLICY_UNREADABLE:{type(exc).__name__}"
    else:
        err = None if pol is not None else "POLICY_ABSENT"
    if pol is None:
        eff = Effective("DISABLED", None, None, None, [err])
    else:
        sha = sha256_bytes(canonical_json(pol))
        issues = (schema_errors(pol) if isinstance(pol, dict) else ["SCHEMA:<root>: not a mapping"]) + \
            (floor_violations(pol) if isinstance(pol, dict) else [])
        req = pol.get("mode") if isinstance(pol, dict) else None
        if issues:
            eff = Effective("DISABLED", req, sha, None, issues)
        elif req in ("DISABLED", "OBSERVE_ONLY"):
            eff = Effective(req, req, sha, pol)
        else:
            kw = {"base": auth_base} if auth_base else {}
            d = authz.find(req, sha, ref=pol.get("authorization_ref"), now=now, **kw)
            eff = Effective(req, req, sha, pol, [], d.authorization_id) if d.allow else \
                Effective("OBSERVE_ONLY", req, sha, pol, [f"MODE_{req}_NOT_AUTHORIZED:{d.code}:{d.reason}"[:300]])
    if log:
        record({"kind": "policy_evaluation", "mode": eff.mode, "requested_mode": eff.requested_mode,
                "policy_sha256": eff.sha256, "authorization_id": eff.authorization_id, "issues": eff.issues[:10]})
    return eff
