"""Deterministic SWE.6 Robot suite scaffold (structure only; every test body is agent-authored).

r59: the DeepSeek SWE.6 test author spent its 20 tool calls exploring (HAL sources, unit tests, globbing for the
suite and the ForgeTarget library, even cppcheck) and never wrote the suite. The structure is derivable from the
inspected SWE.1 baseline: one test case per SWR, tagged with its id, plus the allowed library and its keywords. Each
generated body is `Fail    NOT IMPLEMENTED`, so the suite cannot pass until the author writes real target checks.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

from ..inspection.ears import extract

SUITE = "software/tests/software/test_rcc_requirements.robot"
REQS = "workproducts/SWE.1/software_requirements.md"
MARKER = "# GENERATED by forge_factory.workflow.robot_scaffold"
PLACEHOLDER = "Fail    NOT IMPLEMENTED"

HEADER = f"""{MARKER}: one test case per SWE.1 requirement (names and tags fixed).
# Replace every '{PLACEHOLDER}' line with ForgeTarget keywords. Only 'Library    ForgeTarget' is allowed.
# Keywords (separate arguments with 4 spaces):
#   Run Target Scenario    scn_<topic>.c                      (RCC model: ready flags follow enable bits)
#   Run Target Scenario    scn_<topic>.c    scenario=never_ready   (ready flags never set: waits time out)
#   Target Check Should Pass    <TCHECK number>
#   All Target Checks Should Pass
#   Driver Flash Size Should Be At Most    <bytes>
#   Driver Static RAM Should Be At Most    <bytes>
# Scenario files live next to this suite: software/tests/software/scn_<topic>.c
*** Settings ***
Library    ForgeTarget

*** Test Cases ***
"""


def _doc(text: str) -> str:
    """Requirement text as a Robot-safe single-line documentation (no variables, no escapes, no cell separators)."""
    t = re.sub(r"[^A-Za-z0-9 .,:;()/_=<>+-]", " ", text)
    return re.sub(r"\s+", " ", t).strip()[:160]


def build_suite(markdown: str) -> str:
    cases = [f"{r.req_id}\n    [Documentation]    {_doc(r.text)}\n    [Tags]    {r.req_id}\n    {PLACEHOLDER}: "
             f"{r.req_id}\n" for r in extract(markdown)]
    return HEADER + "\n".join(cases)


def scaffold(ws: Path) -> dict:
    p, req = ws / SUITE, ws / REQS
    if p.is_file():  # never overwrite an authored suite (rework keeps the author's work)
        return {"status": "PASS", "created": False, "file": SUITE}
    if not req.is_file():
        return {"status": "FAIL", "created": False, "file": SUITE, "issue": f"NO_REQUIREMENTS:{REQS}"}
    text = build_suite(req.read_text(encoding="utf-8"))
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, encoding="utf-8")
    return {"status": "PASS", "created": True, "file": SUITE, "test_cases": text.count("[Tags]")}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate the SWE.6 Robot suite skeleton from the SWE.1 requirements")
    ap.add_argument("--workspace", type=Path, default=Path("."))
    a = ap.parse_args(argv)
    out = scaffold(a.workspace.resolve())
    print(json.dumps(out))
    return 0 if out["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
