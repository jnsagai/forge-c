"""Deterministic SWE.4 unit-test harness scaffold (test infrastructure only; test cases are agent-authored).

r16: the 8B test author dropped the CHECK macro from the harness it was asked to write and never wrote a test
body. The harness (host fake register block, register reset, CHECK reporting, main with insertion markers)
carries no test logic, so it is generated; the SWE.4 test author inserts one test function per edit.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

UNIT_TEST = "software/tests/unit/test_rcc.c"
TEST_CASES_MARKER = "// UNIT TEST CASES (SWE.4 test author)"
TEST_CALLS_MARKER = "// UNIT TEST CALLS (SWE.4 test author)"

HARNESS = f"""/* Host unit-test harness GENERATED by forge_factory.workflow.scaffold (no test logic).
 * Test cases below the includes are written by the SWE.4 test author. Host-only evidence, not target. */
#include <stdio.h>
#include <stdint.h>
#include "stm32n6xx_hal_rcc.h"

volatile uint32_t ll_rcc_regs[LL_RCC_REG_COUNT];
static int failures = 0;

#define CHECK(id, cond) do {{ if (cond) {{ printf("%s PASS\\n", (id)); }} \\
    else {{ printf("%s FAIL\\n", (id)); failures++; }} }} while (0)

static void ut_reset_regs(void)
{{
    uint32_t i;
    for (i = 0U; i < LL_RCC_REG_COUNT; i++)
    {{
        ll_rcc_regs[i] = 0U;
    }}
}}

{TEST_CASES_MARKER}

int main(void)
{{
    {TEST_CALLS_MARKER}
    return (failures == 0) ? 0 : 1;
}}
"""


_RESET_FAKE = ("/* Reset the LL test double: empty call log, every LL query returns 0U until scripted (CAPA-038). */\n"
               "static void ut_reset(void)\n{\n    ll_fake_reset();\n}")
HARNESS_FAKE = re.sub(r"static void ut_reset_regs\(void\)\n\{.*?\n\}", lambda _m: _RESET_FAKE, HARNESS.replace(
    '#include "stm32n6xx_hal_rcc.h"\n\nvolatile uint32_t ll_rcc_regs[LL_RCC_REG_COUNT];\n',
    '#define LL_FAKE_IMPLEMENTATION /* defines the LL test double state once, here */\n'
    '#include "stm32n6xx_hal_rcc.h" /* its LL include resolves to software/tests/unit/ll_fake */\n'), count=1, flags=re.S)


def unit_test(ws: Path | None = None) -> str:
    """Feature 009: the unit-test file of the work order's peripheral (RCC: the historical test_rcc.c). Owner
    2026-11-03: work orders with unit_verification write GoogleTest requirement-based tests (test_<id>.cpp); a
    delivery-first declared target harness and a delivered CMSIS header-only driver stay in the C harness."""
    from ..layer import profile, uspec_gtest

    cpp = ws is not None and uspec_gtest(ws) and not _declared_harness(ws) and not _cmsis(ws)
    return f"software/tests/unit/test_{profile(ws)['id']}{'.cpp' if cpp else '.c'}"


def c_harness(ws: Path | None = None) -> str:
    """The self-checking C harness file name (older work orders' unit-test file)."""
    return unit_test(None) if ws is None else re.sub(r"\.cpp$", ".c", unit_test(ws))


def _cmsis(ws: Path) -> bool:
    """A delivered ST CMSIS header-only driver is not valid C++ on a 64-bit host (pointer-to-uint32_t casts of
    register addresses are errors in C++, warnings in C): its unit tests stay in the self-checking C harness."""
    try:
        from ..brownfield.cmsis import is_cmsis

        return is_cmsis(Path(ws))
    except (OSError, ValueError, KeyError):
        return False


def _declared_harness(ws: Path) -> bool:
    try:
        from ..delivery_first import selected as delivery_selected

        cfg, _ = delivery_selected(Path(ws))
        return bool(cfg and cfg.get("unit_harness"))
    except (OSError, ValueError, KeyError, TypeError):
        return False


GTEST_HEAD = """/* Host requirement-based unit tests GENERATED by forge_factory.workflow.scaffold (GoogleTest/GoogleMock 1.11.0,
 * no test logic). One TEST(<unit>, UT_nnn) per row of workproducts/SWE.4/unit_test_plan.md, written by the SWE.4 test
 * author below the marker. The driver C code is compiled as C and linked (forge-tests-mcp run_unit). Host-only
 * evidence, not target. */
#include <cstdint>
#include <cstring>
#include <gtest/gtest.h>
"""
GMOCK_TIME_BASE = """#include <gmock/gmock.h>

/* GoogleMock seam of the HAL time base {tb}() (the design's tick source): without a mock every call advances the host
 * tick by 1 ms (ut_reset() restarts it); a test that must script the tick installs UtTimeBaseMock and sets
 * EXPECT_CALL(m.mock, Tick()) / ON_CALL(m.mock, Tick()). */
class UtTimeBase
{{
public:
    virtual ~UtTimeBase() = default;
    virtual uint32_t Tick() = 0;
}};
class UtTimeBaseMockImpl : public UtTimeBase
{{
public:
    MOCK_METHOD(uint32_t, Tick, (), (override));
}};
static UtTimeBase *ut_time = nullptr;
static uint32_t ut_tick = 0U;
struct UtTimeBaseMock
{{
    ::testing::NiceMock<UtTimeBaseMockImpl> mock;
    UtTimeBaseMock() {{ ut_time = &mock; }}
    ~UtTimeBaseMock() {{ ut_time = nullptr; }}
}};
extern "C" uint32_t {tb}(void)
{{
    if (ut_time != nullptr)
    {{
        return ut_time->Tick();
    }}
    ut_tick++;
    return ut_tick;
}}
"""


def to_gtest(text: str, ws: Path) -> str:
    """The generated C harness as a GoogleTest harness: the same host register store / test double / reset helper,
    the driver headers with C linkage, no CHECK macro and no main (gtest_main)."""
    from ..layer import profile

    tb = profile(ws)["hal"].get("time_base") if "ut_tick" in text else None
    if tb:
        text = re.sub(r"/\* host time base of the HAL.*?\n\}\n", "", text, count=1, flags=re.S)
    text = re.sub(r"\A/\*.*?\*/\n", "", text, count=1, flags=re.S)
    text = text.replace("#include <stdio.h>\n", "").replace("#include <stdint.h>\n", "").replace(
        "#include <string.h>\n", "")
    text = text.replace("#define LL_FAKE_IMPLEMENTATION /* defines the LL test double state once, here */\n", "")
    incs = re.findall(r'^#include ".*$', text, re.M)
    for ln in incs:
        text = text.replace(ln + "\n", "", 1)
    defs = re.findall(r"^#define FORGE_HOST_DEVICE_IMPLEMENTATION.*$", text, re.M)
    for ln in defs:
        text = text.replace(ln + "\n", "", 1)
    text = re.sub(r"static int failures = 0;\n", "", text)
    text = re.sub(r"#define CHECK\(id, cond\).*?while \(0\)\n", "", text, flags=re.S)
    text = re.sub(r"\nint main\(void\)\n\{.*\Z", "\n", text, flags=re.S)
    head = GTEST_HEAD + "".join(d + "\n" for d in defs) + 'extern "C" {\n' + "".join(i + "\n" for i in incs) + "}\n"
    if tb:
        head += GMOCK_TIME_BASE.format(tb=tb)
    return head + "\n" + text.lstrip("\n")


def cmsis_harness(ws: Path) -> str:
    """Harness for a CMSIS delivery: the peripheral instance is a RAM struct (forge_host_device.h), reset by
    ut_reset_regs(); the delivered headers are included unchanged."""
    from ..brownfield import delivered_paths, manifest_of
    from ..brownfield.cmsis import instance

    pfx = instance(ws)
    var = f"forge_host_{pfx.lower()}"
    heads = "".join(f'#include "{Path(h).name}"\n' for h in delivered_paths(manifest_of(ws)) if h.endswith(".h"))
    return (HARNESS.replace('#include "stm32n6xx_hal_rcc.h"\n\nvolatile uint32_t ll_rcc_regs[LL_RCC_REG_COUNT];\n',
                            "#include <string.h>\n#define FORGE_HOST_DEVICE_IMPLEMENTATION /* defines " + var +
                            " once, here */\n#include \"forge_host_device.h\" /* " + pfx + " -> RAM struct " + var +
                            " (host only) */\n" + heads)
            .replace("""    uint32_t i;
    for (i = 0U; i < LL_RCC_REG_COUNT; i++)
    {
        ll_rcc_regs[i] = 0U;
    }""", f"    (void)memset((void *)&{var}, 0, sizeof({var}));"))


def instance_harness(ws: Path, inst: dict) -> str:
    """Instance mode: the LL harness on the pinned device header's RAM instance object (host build: the instance macro
    is that object); defined once here, reset by ut_reset_regs(). No register-block array."""
    obj = inst["host_object"]
    text = HARNESS.replace('#include "stm32n6xx_hal_rcc.h"\n\nvolatile uint32_t ll_rcc_regs[LL_RCC_REG_COUNT];\n',
                           "#include <string.h>\n#define FORGE_HOST_DEVICE_IMPLEMENTATION /* defines " + obj + " once, "
                           "here */\n#include \"stm32n6xx_ll_rcc.h\" /* " + inst["macro"] + " -> RAM instance " + obj +
                           " (host build) */\n").replace("""    uint32_t i;
    for (i = 0U; i < LL_RCC_REG_COUNT; i++)
    {
        ll_rcc_regs[i] = 0U;
    }""", f"    (void)memset((void *)&{obj}, 0, sizeof({obj}));")
    return _for_peripheral(text, ws)


def _time_base(text: str, ws: Path) -> str:
    """SSA-IWDG FND-07: a HAL whose waits are bounded by a system time base gets a deterministic host stub (+1 ms per
    call, reset by ut_reset); identity when the profile names no time base (RCC)."""
    from ..layer import profile

    tb = profile(ws)["hal"].get("time_base")
    if not tb:
        return text
    text = text.replace("static int failures = 0;\n", "static int failures = 0;\n/* host time base of the HAL (+1 ms per "
                        f"call; ut_reset() restarts it) */\nstatic uint32_t ut_tick = 0U;\nuint32_t {tb}(void);\n"
                        f"uint32_t {tb}(void)\n{{\n    ut_tick++;\n    return ut_tick;\n}}\n", 1)
    return text.replace("    ll_fake_reset();\n}", "    ll_fake_reset();\n    ut_tick = 0U;\n}", 1)


def _for_peripheral(text: str, ws: Path) -> str:
    """The RCC harness text with the work order's peripheral names (identity for RCC)."""
    from ..layer import profile

    pr = profile(ws)
    return (text.replace("stm32n6xx_hal_rcc.h", pr["hal"]["header"]).replace("stm32n6xx_ll_rcc.h", pr["ll"]["header"])
            .replace("ll_rcc_regs", pr["ll"]["register_block"]).replace("LL_RCC_REG_COUNT",
                                                                         f"{pr['ll']['function_prefix']}REG_COUNT"))


def scaffold(ws: Path) -> dict:
    """The harness, and (owner 2026-11-03, work orders with unit_verification) the SWE.4 unit test plan: one UT id per
    USPEC item of the frozen SWE.3 unit specification (inspection/uspec_plan)."""
    out = _scaffold(Path(ws))
    from ..layer import uspec_gtest

    if uspec_gtest(ws):
        from ..inspection import uspec_plan as P

        try:
            plan = P.current(ws)
        except P.PlanError as exc:
            return {**out, "status": "FAIL", "issues": [str(exc)]}
        P.write(ws, plan)
        out["plan"] = {"file": P.PLAN_MD, "tests": len(plan["tasks"]), "first_ut": plan["first_ut"],
                       "swe1_trace": plan["swe1_trace"]}
    return out


def _scaffold(ws: Path) -> dict:
    UNIT_TEST = unit_test(ws)  # noqa: N806 - feature 009: per-peripheral file name
    p = ws / UNIT_TEST
    if p.is_file() and TEST_CASES_MARKER in p.read_text(errors="replace"):
        return {"status": "PASS", "created": False, "file": UNIT_TEST}
    if UNIT_TEST.endswith(".cpp"):  # owner 2026-11-03: the GoogleTest form of the same generated harness
        tmp = ws / ".forge-run/lrtx/SWE.4/c-harness-source.c"
        out = _scaffold_c(ws, tmp)
        tmp.parent.mkdir(parents=True, exist_ok=True)
        p.parent.mkdir(parents=True, exist_ok=True)
        p.write_text(to_gtest(tmp.read_text(), ws), encoding="utf-8")
        return {**out, "file": UNIT_TEST, "framework": "googletest-1.11.0"}
    return _scaffold_c(ws, p)


def _scaffold_c(ws: Path, p: Path) -> dict:
    from ..layer import hal_unit_isolation, layer_of

    UNIT_TEST = str(p.relative_to(ws)) if p.is_relative_to(ws) else str(p)  # noqa: N806
    p.parent.mkdir(parents=True, exist_ok=True)
    from ..delivery_first import selected as delivery_selected

    cfg, _ = delivery_selected(ws)
    if cfg and cfg.get("unit_harness"):
        from ..development_demonstration import validate_inputs
        from ..mcp.sdk import ToolContext

        validate_inputs(ws)
        ctx = ToolContext("scaffold", "unit", "swe4-author", "SWE.4", ws.resolve(), "delivery-first")
        text = ctx.path(cfg["unit_harness"], kind="file").read_text()
        if TEST_CASES_MARKER not in text or TEST_CALLS_MARKER not in text:
            raise ValueError("DELIVERY_FIRST_UNIT_HARNESS_MARKERS_MISSING")
        p.write_text(text, encoding="utf-8")
        return {"status": "PASS", "created": True, "file": UNIT_TEST, "declared_target_harness": True}
    from ..brownfield.cmsis import is_cmsis, write_host_device

    if is_cmsis(ws):  # feature 008 (ST pilot): the delivered CMSIS code on the generated host device map
        write_host_device(ws)
        p.write_text(cmsis_harness(ws), encoding="utf-8")
        return {"status": "PASS", "created": True, "file": UNIT_TEST, "host_device": True}
    from ..layer import ll_instance

    inst = ll_instance(ws)
    if inst is not None:  # instance mode: the RAM instance of the pinned device header, no register-block array
        p.write_text(instance_harness(ws, inst), encoding="utf-8")
        return {"status": "PASS", "created": True, "file": UNIT_TEST, "instance": inst["host_object"]}
    if hal_unit_isolation(ws):  # CAPA-038: generated LL test double + harness that uses it
        from .ll_fake import write

        write(ws)
        p.write_text(_time_base(_for_peripheral(HARNESS_FAKE, ws), ws), encoding="utf-8")
        return {"status": "PASS", "created": True, "file": UNIT_TEST, "ll_fake": True}
    text = HARNESS if layer_of(ws) != "LL" else HARNESS.replace('#include "stm32n6xx_hal_rcc.h"',
                                                                  '#include "stm32n6xx_ll_rcc.h"')  # ADR-0009
    p.write_text(_for_peripheral(text, ws), encoding="utf-8")
    return {"status": "PASS", "created": True, "file": UNIT_TEST}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate the SWE.4 host unit-test harness")
    ap.add_argument("--workspace", type=Path, default=Path("."))
    a = ap.parse_args(argv)
    out = scaffold(a.workspace.resolve())
    print(json.dumps(out))
    return 0 if out.get("status") == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
