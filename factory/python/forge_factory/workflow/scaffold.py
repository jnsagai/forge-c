"""Deterministic SWE.4 unit-test harness scaffold (test infrastructure only; test cases are agent-authored).

r16: the 8B test author dropped the CHECK macro from the harness it was asked to write and never wrote a test
body. The harness (host fake register block, register reset, CHECK reporting, main with insertion markers)
carries no test logic, so it is generated; the SWE.4 test author inserts one test function per edit.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

UNIT_TEST = "software/tests/unit/test_rcc.c"
TEST_CASES_MARKER = "// UNIT TEST CASES (SWE.4 test author)"
TEST_CALLS_MARKER = "// UNIT TEST CALLS (SWE.4 test author)"

HARNESS = f"""/* Host unit-test harness GENERATED by forge_factory.workflow.scaffold (no test logic).
 * Test cases below the includes are written by the SWE.4 test author. Host-only evidence, not target. */
#include <stdio.h>
#include <stdint.h>
#include "stm32n6xx_hal_rcc.h"

volatile uint32_t ll_rcc_regs[LL_RCC_REG_COUNT];
static int failures = 0;

#define CHECK(id, cond) do {{ if (cond) {{ printf("%s PASS\\n", (id)); }} \\
    else {{ printf("%s FAIL\\n", (id)); failures++; }} }} while (0)

static void ut_reset_regs(void)
{{
    uint32_t i;
    for (i = 0U; i < LL_RCC_REG_COUNT; i++)
    {{
        ll_rcc_regs[i] = 0U;
    }}
}}

{TEST_CASES_MARKER}

int main(void)
{{
    {TEST_CALLS_MARKER}
    return (failures == 0) ? 0 : 1;
}}
"""


_RESET_FAKE = ("/* Reset the LL test double: empty call log, every LL query returns 0U until scripted (CAPA-038). */\n"
               "static void ut_reset(void)\n{\n    ll_fake_reset();\n}")
HARNESS_FAKE = re.sub(r"static void ut_reset_regs\(void\)\n\{.*?\n\}", lambda _m: _RESET_FAKE, HARNESS.replace(
    '#include "stm32n6xx_hal_rcc.h"\n\nvolatile uint32_t ll_rcc_regs[LL_RCC_REG_COUNT];\n',
    '#define LL_FAKE_IMPLEMENTATION /* defines the LL test double state once, here */\n'
    '#include "stm32n6xx_hal_rcc.h" /* its LL include resolves to software/tests/unit/ll_fake */\n'), count=1, flags=re.S)


def unit_test(ws: Path | None = None) -> str:
    """Feature 009: the unit-test file of the work order's peripheral (RCC: the historical test_rcc.c)."""
    from ..layer import profile

    return f"software/tests/unit/test_{profile(ws)['id']}.c"


def _for_peripheral(text: str, ws: Path) -> str:
    """The RCC harness text with the work order's peripheral names (identity for RCC)."""
    from ..layer import profile

    pr = profile(ws)
    return (text.replace("stm32n6xx_hal_rcc.h", pr["hal"]["header"]).replace("stm32n6xx_ll_rcc.h", pr["ll"]["header"])
            .replace("ll_rcc_regs", pr["ll"]["register_block"]).replace("LL_RCC_REG_COUNT",
                                                                         f"{pr['ll']['function_prefix']}REG_COUNT"))


def scaffold(ws: Path) -> dict:
    from ..layer import hal_unit_isolation, layer_of

    UNIT_TEST = unit_test(ws)  # noqa: N806 - feature 009: per-peripheral file name
    p = ws / UNIT_TEST
    if p.is_file() and TEST_CASES_MARKER in p.read_text(errors="replace"):
        return {"status": "PASS", "created": False, "file": UNIT_TEST}
    p.parent.mkdir(parents=True, exist_ok=True)
    if hal_unit_isolation(ws):  # CAPA-038: generated LL test double + harness that uses it
        from .ll_fake import write

        write(ws)
        p.write_text(_for_peripheral(HARNESS_FAKE, ws), encoding="utf-8")
        return {"status": "PASS", "created": True, "file": UNIT_TEST, "ll_fake": True}
    text = HARNESS if layer_of(ws) != "LL" else HARNESS.replace('#include "stm32n6xx_hal_rcc.h"',
                                                                  '#include "stm32n6xx_ll_rcc.h"')  # ADR-0009
    p.write_text(_for_peripheral(text, ws), encoding="utf-8")
    return {"status": "PASS", "created": True, "file": UNIT_TEST}


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description="Generate the SWE.4 host unit-test harness")
    ap.add_argument("--workspace", type=Path, default=Path("."))
    a = ap.parse_args(argv)
    print(json.dumps(scaffold(a.workspace.resolve())))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
