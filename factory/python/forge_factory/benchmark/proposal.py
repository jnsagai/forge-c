"""Feature 020 FR-029 (SC-010): the way-of-working proposal for future modules.

Inputs: the pilot decision log (append-only Markdown table, FR-028), a classification file that says for each adopted
entry whether its rule becomes a default, stays a per-order setting or remains pilot-only (and what the ladder drivers
would need to adopt it), and the comparison directory (benchmark/compare.py). Output: Markdown in which every rule
cites its decision-log entry. Refusals (exit 2, nothing written): an adopted entry not classified, a class naming an
entry the log does not have, a rule built on an entry that is not adopted, a missing comparison.

    python -m forge_factory.benchmark.proposal --log decision-log.md --classes way-of-working-classes.yaml \\
        --metrics <comparison dir> --out way-of-working-proposal.md
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

import yaml

CLASSES_SCHEMA = "forge-c/way-of-working-classes/1"
CLASSES = {"default": "Default rules", "per_order": "Per-order settings", "pilot_only": "Pilot-only (not proposed)"}
COLS = ("id", "date", "rule", "decided_by", "rationale", "evidence", "status")
ROW = re.compile(r"^\|\s*(D\d+)\s*\|")


class Refused(Exception):
    pass


def parse_log(text: str) -> dict[str, dict]:
    out = {}
    for line in text.splitlines():
        if not ROW.match(line):
            continue
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if len(cells) != len(COLS):
            raise Refused(f"PROPOSAL_LOG_ROW: {cells[0]} has {len(cells)} cells, expected {len(COLS)}")
        out[cells[0]] = dict(zip(COLS, cells))
    return out


DECIDED = ("adopted", "pilot")  # "pilot": in force for the pilot, to be classified like an adopted rule


def adopted(entry: dict) -> bool:
    return entry["status"].split()[0] in DECIDED


def build(log: dict[str, dict], classes: dict, comparison: dict) -> str:
    if classes.get("schema") != CLASSES_SCHEMA:
        raise Refused(f"PROPOSAL_CLASSES_SCHEMA: expected {CLASSES_SCHEMA}")
    rules = classes.get("rules") or []
    for r in rules:
        if r["id"] not in log:
            raise Refused(f"PROPOSAL_UNKNOWN_ENTRY: {r['id']}")
        if not adopted(log[r["id"]]):
            raise Refused(f"PROPOSAL_NOT_ADOPTED: {r['id']} is {log[r['id']]['status']}")
        if r.get("class") not in CLASSES:
            raise Refused(f"PROPOSAL_CLASS: {r['id']} class {r.get('class')!r} not in {sorted(CLASSES)}")
    done = {r["id"] for r in rules}
    missing = [i for i, e in log.items() if adopted(e) and i not in done]
    if missing:
        raise Refused(f"PROPOSAL_UNCLASSIFIED: {', '.join(missing)}")
    md = ["# Way-of-working proposal for future modules", "",
          "Generated by `forge_factory.benchmark.proposal` from the pilot decision log, its classification and the "
          "benchmark comparison. Every rule cites its decision-log entry; the evidence is in the log.", ""]
    for cls, title in CLASSES.items():
        md += [f"## {title}", ""]
        md += [f"- {r['rule'].strip()} ({r['id']})" for r in rules if r["class"] == cls] or ["- none (no entry)"]
        md.append("")
    md += ["## What the ladder drivers would need", ""]
    md += [f"- {r['ladder_need'].strip()} ({r['id']})" for r in rules if r.get("ladder_need")] or ["- nothing (no entry)"]
    md += ["", "## Entries not proposed", ""]
    md += [f"- {i}: {e['status']}" for i, e in log.items() if not adopted(e)] or ["- none"]
    md += ["", "## Comparison (metrics only)", "", "| metric | category | pilot | benchmark |", "|---|---|---|---|"]
    md += [f"| {r['metric']} | {r['category']} | {_cell(r['pilot'])} | {_cell(r['benchmark'])} |"
           for r in comparison.get("rows") or []]
    md += ["", "Not delivered: " + (", ".join(comparison.get("not_delivered") or []) or "none"), ""]
    return "\n".join(md)


def _cell(v) -> str:
    if v is None:
        return "not reported"
    return f"{v:.3f}".rstrip("0").rstrip(".") if isinstance(v, float) else str(v)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(prog="forge_factory.benchmark.proposal")
    ap.add_argument("--log", required=True, type=Path)
    ap.add_argument("--classes", required=True, type=Path)
    ap.add_argument("--metrics", required=True, type=Path)
    ap.add_argument("--out", required=True, type=Path)
    a = ap.parse_args(argv)
    try:
        cmp_ = a.metrics / "comparison.json"
        if not cmp_.is_file():
            raise Refused(f"PROPOSAL_METRICS_MISSING: {cmp_}")
        md = build(parse_log(a.log.read_text()), yaml.safe_load(a.classes.read_text()), json.loads(cmp_.read_text()))
    except Refused as e:
        print(str(e), file=sys.stderr)
        return 2
    a.out.write_text(md)
    print(json.dumps({"status": "OK", "out": str(a.out)}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
