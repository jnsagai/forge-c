"""Feature 008 follow-up (owner 2026-10-20, "address all"; proposal checklist-v0.4-brownfield, ST pilot): host and
target builds of a CMSIS-style vendor delivery (e.g. ST STM32CubeN6 LL code that accesses `RCC->CR`).

* host (unit and integration tests): the CMSIS core headers are Arm-only (inline assembly, arm_acle.h), so a generated
  host device directory holds unmodified copies of the vendor DEVICE headers next to a host stub of the core header,
  and `forge_host_device.h` maps the peripheral instance (`RCC`) to a RAM struct `forge_host_<ppp>` (defined once by
  the test that defines FORGE_HOST_DEVICE_IMPLEMENTATION). The delivered code is compiled unchanged.
* target (Renode images): the vendor include directory, the delivery's defines and -mcmse for a secure build (ST's
  RCC is then RCC_S at the secure base the platform maps).

The directory is generated test infrastructure (never agent-written): tests reference it, run_unit regenerates it."""
from __future__ import annotations

import shutil
from pathlib import Path

from . import is_brownfield, manifest_of

HOST_DIR = "software/tests/host_device"
VENDOR_DIR = "inputs/vendor/include"
CORE_STUB = """/* GENERATED by forge_factory.brownfield.cmsis - host stub of the CMSIS Cortex-M55 core header for HOST unit and
 * integration tests only: register qualifiers, no-op barriers, single-core exclusive access (the load is a plain
 * read, the store always succeeds: what one host thread observes) and __CLZ/__RBIT; no core peripherals. Target builds use the
 * delivered vendor core header. Do not edit. */
#ifndef FORGE_HOST_CORE_CM55_H
#define FORGE_HOST_CORE_CM55_H
#include <stdint.h>
#define __I volatile const
#define __O volatile
#define __IO volatile
#define __IM volatile const
#define __OM volatile
#define __IOM volatile
#define __STATIC_INLINE static inline
#define __STATIC_FORCEINLINE static inline
#define __NOP() ((void)0)
#define __DSB() ((void)0)
#define __ISB() ((void)0)
#define __DMB() ((void)0)
/* stm32n6xx.h ATOMIC_SET_BIT / ATOMIC_MODIFY_REG ... (F015: ST USART LL; undeclared before, clang_analyze FAILED) */
static inline uint32_t __LDREXW(volatile uint32_t *addr) { return *addr; }
static inline uint32_t __STREXW(uint32_t value, volatile uint32_t *addr) { *addr = value; return 0U; }
static inline uint16_t __LDREXH(volatile uint16_t *addr) { return *addr; }
static inline uint32_t __STREXH(uint16_t value, volatile uint16_t *addr) { *addr = value; return 0U; }
/* stm32n6xx.h POSITION_VAL(VAL) = __CLZ(__RBIT(VAL)) (F015: ST GPIO LL; host unit tests did not build), Arm semantics */
static inline uint8_t __CLZ(uint32_t value)
{ uint8_t n = 0U; if (value == 0U) { return 32U; } while ((value & 0x80000000U) == 0U) { value <<= 1U; n++; } return n; }
static inline uint32_t __RBIT(uint32_t value)
{ uint32_t r = 0U; for (uint32_t i = 0U; i < 32U; i++) { r = (r << 1U) | ((value >> i) & 1U); } return r; }
#endif
"""


def style(ws: Path) -> str:
    m = manifest_of(ws)
    return (m.get("delivery") or {}).get("build", {}).get("style", "forge") if is_brownfield(m) else "greenfield"


def is_cmsis(ws: Path) -> bool:
    return style(ws) == "cmsis"


def build_settings(ws: Path) -> dict:
    return (manifest_of(ws).get("delivery") or {}).get("build") or {}


def instance(ws: Path) -> str:
    from ..layer import register_prefix

    return register_prefix(ws)


def host_header(ws: Path) -> str:
    pfx = instance(ws)
    var = f"forge_host_{pfx.lower()}"
    return f"""/* GENERATED by forge_factory.brownfield.cmsis - host device mapping for HOST tests of the delivered CMSIS code:
 * the vendor device header unchanged, then the peripheral instance {pfx} mapped to the RAM struct {var}. Define
 * FORGE_HOST_DEVICE_IMPLEMENTATION in exactly one test file before including this header. Do not edit. */
#ifndef FORGE_HOST_DEVICE_H
#define FORGE_HOST_DEVICE_H
#include "stm32n6xx.h"
extern {pfx}_TypeDef {var};
#undef {pfx}
#define {pfx} (&{var})
#ifdef FORGE_HOST_DEVICE_IMPLEMENTATION
{pfx}_TypeDef {var};
#endif
#endif
"""


def write_host_device(ws: Path) -> bool:
    """Generate the host device directory; False when the work order is not a CMSIS delivery."""
    ws = Path(ws)
    if not is_cmsis(ws):
        return False
    src, out = ws / VENDOR_DIR, ws / HOST_DIR
    if out.exists():
        for p in out.iterdir():
            p.chmod(0o644)
        shutil.rmtree(out)
    out.mkdir(parents=True)
    for h in sorted(src.glob("*.h")):  # device headers only: the core/compiler headers are Arm-only
        if not (h.name.startswith("core_") or h.name.startswith("cmsis_")):
            shutil.copyfile(h, out / h.name)
    (out / "core_cm55.h").write_text(CORE_STUB)
    (out / "forge_host_device.h").write_text(host_header(ws))
    for p in out.iterdir():
        p.chmod(0o444)
    return True


def host_flags(ws: Path) -> list[str]:
    """Host compiler flags for a CMSIS delivery (the host device directory first); [] otherwise."""
    if not is_cmsis(ws):
        return []
    write_host_device(ws)
    # CAPA-056: third-party headers are system headers (their warnings are not the delivery's or the factory's)
    return ["-isystem", str(Path(ws) / HOST_DIR), *[f"-D{d}" for d in build_settings(ws).get("defines") or []]]


def target_flags(ws: Path) -> list[str]:
    """Target (Cortex-M55) flags for a CMSIS delivery: vendor includes, defines, -mcmse for a secure build."""
    if not is_cmsis(ws):
        return []
    b = build_settings(ws)
    return ["-isystem", str(Path(ws) / VENDOR_DIR), *[f"-D{d}" for d in b.get("defines") or []],
            *(["-mcmse"] if b.get("secure") else [])]


def delivered_unit(ws: Path, out_dir: Path) -> Path | None:
    """Build-only compile unit for a header-only delivery (ST LL): the delivered headers and one non-inline wrapper per
    scope function, so the compilers, the analyzer and the size/stack tools see exactly the scope. Written to the
    tool's output directory, never into the workspace (the delivery is not changed). None when not applicable."""
    import json
    import re

    from . import DELIVERY_DIR, delivered_paths

    ws = Path(ws)
    m = manifest_of(ws)
    if not is_brownfield(m):
        return None
    headers = [p for p in delivered_paths(m) if p.endswith(".h")]
    try:
        scope = [f["name"] for f in json.loads((ws / DELIVERY_DIR / "scope.json").read_text()).get("functions", [])]
    except (OSError, ValueError):
        scope = []
    text = "\n".join((ws / h).read_text(errors="replace") for h in headers if (ws / h).is_file())
    code = re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)
    lines = ["/* GENERATED build-only unit (forge_factory.brownfield.cmsis): delivered headers + scope wrappers */",
             *[f'#include "{Path(h).name}"' for h in headers]]
    for name in scope:
        sig = re.search(r"^[ \t]*(?:__STATIC_INLINE|__STATIC_FORCEINLINE|static[ \t]+inline)[ \t]+"
                        r"([A-Za-z_][\w \t]*?[\w*])[ \t]+" + re.escape(name) + r"\s*\(([^)]*)\)\s*\{", code, re.M)
        if not sig:
            continue
        ret, params = " ".join(sig.group(1).split()), sig.group(2).strip()
        args = [] if params in ("", "void") else [re.search(r"([A-Za-z_]\w*)\s*$", p.strip()).group(1)
                                                   for p in params.split(",")]
        decl = f"{ret} forge_measure_{name}({params or 'void'})"
        lines += [f"{decl};", f"{decl} {{ {'' if ret == 'void' else 'return '}{name}({', '.join(args)}); }}"]
    if len(lines) == 1 + len(headers):
        return None
    out = Path(out_dir) / "forge_delivered_unit.c"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    return out
