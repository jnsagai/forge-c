"""Feature 008 follow-up (owner 2026-10-20, "address all"; proposal checklist-v0.4-brownfield, ST pilot): host and
target builds of a CMSIS-style vendor delivery (e.g. ST STM32CubeN6 LL code that accesses `RCC->CR`).

* host (unit and integration tests): the CMSIS core headers are Arm-only (inline assembly, arm_acle.h), so a generated
  host device directory holds unmodified copies of the vendor DEVICE headers next to a host stub of the core header,
  and `forge_host_device.h` maps the peripheral instance (`RCC`) to a RAM struct `forge_host_<ppp>` (defined once by
  the test that defines FORGE_HOST_DEVICE_IMPLEMENTATION). The delivered code is compiled unchanged.
* target (Renode images): the vendor include directory, the delivery's defines and -mcmse for a secure build (ST's
  RCC is then RCC_S at the secure base the platform maps).

The directory is generated test infrastructure (never agent-written): tests reference it, run_unit regenerates it.

CAPA-128 (WO-F014-SWE3-CRCHAL-20261103-L27): a HAL work order on a PROVIDED CMSIS LL (ST's FROZEN LL from a verified
brownfield LL work order, --provided-from) gets the same build inputs as that LL work order: its vendor include files
(hash-bound to the source manifest, `provided_build` in the HAL manifest), its defines and secure setting, the same
host device directory and the same target flags. The HAL's own compile units pass the instance macro (`CRC`) to the
LL, so on the host every compile unit sees the RAM mapping (`-include forge_host_device.h`, a weak definition)."""
from __future__ import annotations

import shutil
from pathlib import Path

from . import is_brownfield, manifest_of

HOST_DIR = "software/tests/host_device"
VENDOR_DIR = "inputs/vendor/include"
PROVIDED_BUILD = "provided_build"  # manifest key of a HAL work order on a provided CMSIS LL (CAPA-128)
GTEST_LINKAGE_FIELD = "cmsis_host_test_linkage"
GTEST_LINKAGE = "c-abi-gtest-v1"


def gtest_linkage(manifest: dict) -> bool:
    """Fresh CMSIS orders opt into the C/C++ ABI; missing bindings retain the historical C harness."""
    if GTEST_LINKAGE_FIELD not in manifest:
        return False
    if manifest[GTEST_LINKAGE_FIELD] != GTEST_LINKAGE:
        raise ValueError("CMSIS_HOST_TEST_LINKAGE_INVALID")
    return True


CORE_STUB = """/* GENERATED by forge_factory.brownfield.cmsis - host stub of the CMSIS Cortex-M55 core header for HOST unit and
 * integration tests only: register qualifiers, no-op barriers, single-core exclusive access (the load is a plain
 * read, the store always succeeds: what one host thread observes) and __CLZ/__RBIT; no core peripherals. Target builds use the
 * delivered vendor core header. Do not edit. */
#ifndef FORGE_HOST_CORE_CM55_H
#define FORGE_HOST_CORE_CM55_H
#include <stdint.h>
#define __I volatile const
#define __O volatile
#define __IO volatile
#define __IM volatile const
#define __OM volatile
#define __IOM volatile
#define __STATIC_INLINE static inline
#define __STATIC_FORCEINLINE static inline
#define __NOP() ((void)0)
#define __DSB() ((void)0)
#define __ISB() ((void)0)
#define __DMB() ((void)0)
/* stm32n6xx.h ATOMIC_SET_BIT / ATOMIC_MODIFY_REG ... (F015: ST USART LL; undeclared before, clang_analyze FAILED) */
static inline uint32_t __LDREXW(volatile uint32_t *addr) { return *addr; }
static inline uint32_t __STREXW(uint32_t value, volatile uint32_t *addr) { *addr = value; return 0U; }
static inline uint16_t __LDREXH(volatile uint16_t *addr) { return *addr; }
static inline uint32_t __STREXH(uint16_t value, volatile uint16_t *addr) { *addr = value; return 0U; }
/* stm32n6xx.h POSITION_VAL(VAL) = __CLZ(__RBIT(VAL)) (F015: ST GPIO LL; host unit tests did not build), Arm semantics */
static inline uint8_t __CLZ(uint32_t value)
{ uint8_t n = 0U; if (value == 0U) { return 32U; } while ((value & 0x80000000U) == 0U) { value <<= 1U; n++; } return n; }
static inline uint32_t __RBIT(uint32_t value)
{ uint32_t r = 0U; for (uint32_t i = 0U; i < 32U; i++) { r = (r << 1U) | ((value >> i) & 1U); } return r; }
#endif
"""


def style(ws: Path) -> str:
    m = manifest_of(ws)
    return (m.get("delivery") or {}).get("build", {}).get("style", "forge") if is_brownfield(m) else "greenfield"


def is_cmsis(ws: Path) -> bool:
    return style(ws) == "cmsis"


def build_settings(ws: Path) -> dict:
    return (manifest_of(ws).get("delivery") or {}).get("build") or {}


def provided_build(ws: Path) -> dict | None:
    """CAPA-128: the vendor build inputs a HAL work order received with its provided CMSIS LL; None otherwise."""
    if is_cmsis(ws):
        return None
    pb = manifest_of(ws).get(PROVIDED_BUILD)
    return pb if isinstance(pb, dict) and pb.get("style") == "cmsis" else None


def vendor_build(ws: Path) -> dict | None:
    """The CMSIS build settings of the work order: its own delivery's, or (CAPA-128) the provided LL's; None for
    every other work order (greenfield, forge-style deliveries)."""
    return build_settings(ws) if is_cmsis(ws) else provided_build(ws)


def provided_inputs(source_ws: Path) -> tuple[dict[str, bytes], dict] | None:
    """CAPA-128, workorder.prepare of a HAL work order: the build inputs of a provided CMSIS LL - the source LL work
    order's vendor include files (each byte-identical to its sha256 in the source manifest, else refused), defines and
    secure setting - and the `provided_build` record. None when the source LL is not a CMSIS delivery (greenfield)."""
    from ..common import sha256_bytes

    src = Path(source_ws)
    if not is_cmsis(src):
        return None
    m = manifest_of(src)
    wo = m.get("work_order") or src.parent.name
    data, files = {}, []
    for d in m.get("delivered") or []:
        rel = str(d.get("path") or "")
        if d.get("role") != "delivered_dependency" or not rel.startswith(VENDOR_DIR + "/"):
            continue
        p = src / rel
        raw = p.read_bytes() if p.is_file() else None
        if raw is None or sha256_bytes(raw) != d.get("sha256"):
            raise ValueError(f"PROVIDED_BUILD_INPUT_MISMATCH:{wo}:{rel}")
        data[rel] = raw
        files.append({"path": rel, "sha256": d["sha256"], "bytes": len(raw),
                      **{k: d[k] for k in ("origin", "licence") if k in d}})
    if not files:
        raise ValueError(f"PROVIDED_BUILD_INPUTS_MISSING:{wo}:{VENDOR_DIR}")
    b = build_settings(src)
    return data, {"style": "cmsis", "source_work_order": wo, "defines": list(b.get("defines") or []),
                  "secure": bool(b.get("secure")), "files": files,
                  "rule": "read-only vendor build inputs of the provided LL, byte-identical to its work order (CAPA-128)"}


def _verify_provided(ws: Path, pb: dict) -> None:
    from ..common import sha256_file

    for f in pb.get("files") or []:
        p = Path(ws) / f["path"]
        if not p.is_file() or sha256_file(p) != f["sha256"]:
            raise ValueError(f"PROVIDED_BUILD_INPUT_CHANGED:{f['path']}")


def instance(ws: Path) -> str:
    from ..layer import register_prefix

    return register_prefix(ws)


def host_header(ws: Path) -> str:
    pfx = instance(ws)
    var = f"forge_host_{pfx.lower()}"
    if provided_build(ws) is not None:  # CAPA-128: force-included into every host compile unit of the HAL
        return f"""/* GENERATED by forge_factory.brownfield.cmsis - host device mapping for HOST builds of a HAL on the
 * provided CMSIS LL: the vendor device header unchanged, then the peripheral instance {pfx} mapped to the RAM struct {var}.
 * Every host compile unit includes it first (-include), so the HAL's own calls with {pfx} reach the RAM struct; one
 * weak definition is shared by all units (tests read and preset {var}). Do not edit. */
#ifndef FORGE_HOST_DEVICE_H
#define FORGE_HOST_DEVICE_H
#include "stm32n6xx.h"
#ifdef __cplusplus
extern "C" {{
#endif
__attribute__((weak)) {pfx}_TypeDef {var};
#ifdef __cplusplus
}}
#endif
#undef {pfx}
#define {pfx} (&{var})
#endif
"""
    text = f"""/* GENERATED by forge_factory.brownfield.cmsis - host device mapping for HOST tests of the delivered CMSIS code:
 * the vendor device header unchanged, then the peripheral instance {pfx} mapped to the RAM struct {var}. Define
 * FORGE_HOST_DEVICE_IMPLEMENTATION in exactly one test file before including this header. Do not edit. */
#ifndef FORGE_HOST_DEVICE_H
#define FORGE_HOST_DEVICE_H
#include "stm32n6xx.h"
extern {pfx}_TypeDef {var};
#undef {pfx}
#define {pfx} (&{var})
#ifdef FORGE_HOST_DEVICE_IMPLEMENTATION
{pfx}_TypeDef {var};
#endif
#endif
"""
    if gtest_linkage(manifest_of(ws)):
        # The C driver and GoogleTest C++ unit must resolve the same RAM object,
        # including when a caller includes this generated shim outside extern C.
        text = text.replace(f"extern {pfx}_TypeDef {var};", f"#ifdef __cplusplus\nextern \"C\" {{\n#endif\n"
                            f"extern {pfx}_TypeDef {var};")
        text = text.replace(f"{pfx}_TypeDef {var};\n#endif\n#endif\n",
                            f"{pfx}_TypeDef {var};\n#endif\n#ifdef __cplusplus\n}}\n#endif\n#endif\n")
    return text


def write_host_device(ws: Path) -> bool:
    """Generate the host device directory; False when the work order is not a CMSIS delivery (or a HAL on one)."""
    ws = Path(ws)
    pb = provided_build(ws)
    if not is_cmsis(ws) and pb is None:
        return False
    if pb is not None:
        _verify_provided(ws, pb)
    src, out = ws / VENDOR_DIR, ws / HOST_DIR
    if out.exists():
        for p in out.iterdir():
            p.chmod(0o644)
        shutil.rmtree(out)
    out.mkdir(parents=True)
    for h in sorted(src.glob("*.h")):  # device headers only: the core/compiler headers are Arm-only
        if not (h.name.startswith("core_") or h.name.startswith("cmsis_")):
            shutil.copyfile(h, out / h.name)
    (out / "core_cm55.h").write_text(CORE_STUB)
    (out / "forge_host_device.h").write_text(host_header(ws))
    for p in out.iterdir():
        p.chmod(0o444)
    return True


def host_flags(ws: Path, force_include: bool = True) -> list[str]:
    """Host compiler flags for a CMSIS delivery (the host device directory first); [] otherwise. CAPA-128: a HAL on a
    provided CMSIS LL gets the same flags plus the forced host mapping (force_include=False for cppcheck, which takes
    no -include)."""
    b = vendor_build(ws)
    if b is None:
        return []
    write_host_device(ws)
    hd = Path(ws) / HOST_DIR
    forced = ["-include", str(hd / "forge_host_device.h")] if force_include and provided_build(ws) is not None else []
    # CAPA-056: third-party headers are system headers (their warnings are not the delivery's or the factory's)
    return ["-isystem", str(hd), *forced, *[f"-D{d}" for d in b.get("defines") or []]]


def target_flags(ws: Path) -> list[str]:
    """Target (Cortex-M55) flags for a CMSIS delivery: vendor includes, defines, -mcmse for a secure build (CAPA-128:
    also for a HAL on a provided CMSIS LL)."""
    b = vendor_build(ws)
    if b is None:
        return []
    if not is_cmsis(ws):
        _verify_provided(ws, b)
    return ["-isystem", str(Path(ws) / VENDOR_DIR), *[f"-D{d}" for d in b.get("defines") or []],
            *(["-mcmse"] if b.get("secure") else [])]


def delivered_unit(ws: Path, out_dir: Path) -> Path | None:
    """Build-only compile unit for a header-only delivery (ST LL): the delivered headers and one non-inline wrapper per
    scope function, so the compilers, the analyzer and the size/stack tools see exactly the scope. Written to the
    tool's output directory, never into the workspace (the delivery is not changed). None when not applicable."""
    import json
    import re

    from . import DELIVERY_DIR, delivered_paths

    ws = Path(ws)
    m = manifest_of(ws)
    if not is_brownfield(m):
        return None
    headers = [p for p in delivered_paths(m) if p.endswith(".h")]
    try:
        scope = [f["name"] for f in json.loads((ws / DELIVERY_DIR / "scope.json").read_text()).get("functions", [])]
    except (OSError, ValueError):
        scope = []
    text = "\n".join((ws / h).read_text(errors="replace") for h in headers if (ws / h).is_file())
    code = re.sub(r"/\*.*?\*/|//[^\n]*", "", text, flags=re.S)
    lines = ["/* GENERATED build-only unit (forge_factory.brownfield.cmsis): delivered headers + scope wrappers */",
             *[f'#include "{Path(h).name}"' for h in headers]]
    for name in scope:
        sig = re.search(r"^[ \t]*(?:__STATIC_INLINE|__STATIC_FORCEINLINE|static[ \t]+inline)[ \t]+"
                        r"([A-Za-z_][\w \t]*?[\w*])[ \t]+" + re.escape(name) + r"\s*\(([^)]*)\)\s*\{", code, re.M)
        if not sig:
            continue
        ret, params = " ".join(sig.group(1).split()), sig.group(2).strip()
        args = [] if params in ("", "void") else [re.search(r"([A-Za-z_]\w*)\s*$", p.strip()).group(1)
                                                   for p in params.split(",")]
        decl = f"{ret} forge_measure_{name}({params or 'void'})"
        lines += [f"{decl};", f"{decl} {{ {'' if ret == 'void' else 'return '}{name}({', '.join(args)}); }}"]
    if len(lines) == 1 + len(headers):
        return None
    out = Path(out_dir) / "forge_delivered_unit.c"
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n")
    return out


def provided_api(ws: Path) -> dict | None:
    """CAPA-131: the instance API of a HAL work order's provided LL, derived from the provided header: the LL functions
    whose first parameter is the CMSIS instance pointer (`CRC_TypeDef *CRCx`), the instance macro (`CRC`) and their
    signatures. None for every other work order (a greenfield register-array LL has no instance parameter)."""
    import re
    from collections import Counter

    from ..layer import layer_of, ll_header

    ws = Path(ws)
    p = ws / ll_header(ws)
    if layer_of(ws) != "HAL" or not p.is_file():
        return None
    code = re.sub(r"/\*.*?\*/|//[^\n]*", "", p.read_text(errors="replace"), flags=re.S)
    sigs, calls, inst = {}, {}, Counter()
    for m in re.finditer(r"\b(?:__STATIC_(?:FORCE)?INLINE|static\s+inline)\s+((?:const\s+)?\w+[\s*]+?)(LL_\w+)\s*"
                         r"\(([^)]*)\)\s*\{", code):
        t = re.match(r"\s*(?:const\s+)?([A-Za-z]\w*)_TypeDef\s*\*\s*\w+\s*$", m.group(3).split(",")[0])
        if t:
            inst[t.group(1)] += 1
            sigs[m.group(2)] = f"{' '.join(m.group(1).split())} {m.group(2)}({' '.join(m.group(3).split())})"
            calls[m.group(2)] = [re.findall(r"\w+", a)[-1] for a in m.group(3).split(",")[1:] if a.strip()]
    if not sigs:
        return None
    macro = inst.most_common(1)[0][0]
    return {"instance": macro, "functions": sorted(sigs), "signatures": sigs,
            "calls": {n: f"{n}({', '.join([macro, *a])})" for n, a in calls.items()}}
