"""T007 — role- and phase-aware tool authorization, independent of prompts.

Enforced in two places (defence in depth):
 1. Fabro blocking host `pre_tool_use` command hook (`forge_factory.policy.fabro_hook`) for EVERY tool,
    including Fabro native shell/file/web/sub-agent tools (ADR-0002 limitation 1).
 2. Inside every Forge MCP server (`mcp/sdk.py`) using FORGE_ROLE/FORGE_PHASE from the run binding.

A *run binding* maps workflow node IDs to roles/phases and fixes the product workspace. It is
generated by the deterministic workflow builder (T009/T018), never by an agent.
"""
from __future__ import annotations

import fnmatch
import json
import os
import re
from dataclasses import dataclass, field
from pathlib import Path, PurePosixPath

import yaml

from ..common import CONFIG_DIR
from ..registry.agents import AgentDefinition, load_agents
from ..registry.mcp_registry import load_registry, op_from_fabro_tool

READ_TOOLS = {"read_file", "read_many_files", "grep", "glob", "list_dir"}
WRITE_TOOLS = {"write_file", "edit_file", "apply_patch"}
DENY_NATIVE = {"shell": "NATIVE_SHELL_DENIED", "web_search": "NETWORK_DENIED", "web_fetch": "NETWORK_DENIED",
               "spawn_agent": "SUBAGENT_DENIED", "send_input": "SUBAGENT_DENIED", "wait": "SUBAGENT_DENIED",
               "close_agent": "SUBAGENT_DENIED"}
NO_SIDE_EFFECT = {"update_plan", "TaskCreate", "TaskUpdate", "TaskGet", "TaskList"}

# Paths no production agent may write through native tools (safety/QA policy, skills, specs, evidence).
ALWAYS_PROTECTED = [".fabro/**", ".specify/**", ".forge-run/**", "inputs/**", "specs/**", "config/**", "factory/**", ".git/**",
                    "policies/**", "safety/approved/**", "archives/**", "evidence/**", "configuration/approved/**",
                    "inspection/**", "quality/**"]
SECRET_READ_DENY = [".git/**", "**/.env", "**/*.key", "**/*.pem", "secrets/**", "**/server.env", "**/auth.json"]
PRODUCT_PATHS = ["software/**", "workproducts/**", "safety/**", "traceability/**", "verification/**",
                 "drivers/**", "inspection/**"]

ROLE_WRITE_PREFIXES: dict[str, list[str]] = {
    "onboard-model-author": ["onboarding/model/"],
    "swe1-author": ["workproducts/SWE.1/", "safety/software_safety_requirements.md", "traceability/"],
    "swe2-author": ["workproducts/SWE.2/"],
    "swe3-author": ["workproducts/SWE.3/", "software/src/", "software/include/", "software/hal/", "software/ll/"],
    "swe4-author": ["workproducts/SWE.4/", "software/tests/unit/"],
    "swe5-author": ["workproducts/SWE.5/", "software/tests/integration/", "software/tests/target/"],
    "swe6-author": ["workproducts/SWE.6/", "software/tests/software/"],
    "footprint-optimizer": ["software/src/", "software/include/", "reports/footprint-optimizer/"],
    "intake-analyst": ["reports/intake-analyst/"],
    "fabric-repair": ["repair/", "runtime/", "services/"],  # infra repo repairable allowlist (repair/infra.py)
    "mcp-integrator": ["repair/", "runtime/", "services/"],
}


@dataclass
class Decision:
    allow: bool
    code: str
    reason: str
    role: str | None = None
    op: str | None = None

    def hook_json(self) -> str:
        return json.dumps({"decision": "proceed" if self.allow else "block",
                           "reason": f"FORGE_POLICY:{self.code}:{self.reason}"[:200]})


@dataclass
class Binding:
    binding_id: str
    workspace: str
    nodes: dict[str, dict] = field(default_factory=dict)  # node_id -> {"role":..., "phase":...}

    @classmethod
    def load(cls, path: Path) -> Binding:
        d = json.loads(path.read_text(encoding="utf-8"))
        return cls(d["binding_id"], d["workspace"], d["nodes"])

    def dump(self, path: Path) -> None:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps({"binding_id": self.binding_id, "workspace": self.workspace,
                                    "nodes": self.nodes}, indent=2, sort_keys=True), encoding="utf-8")


def _match(rel: str, globs: list[str]) -> bool:
    return any(fnmatch.fnmatchcase(rel, g) or fnmatch.fnmatchcase(rel + "/", g) or rel == g.rstrip("/*")
               for g in globs)


def _protected_from_supervisor_policy() -> list[str]:
    try:
        pol = yaml.safe_load((CONFIG_DIR / "supervisor-policy.yaml").read_text())
        return list(pol.get("protected_paths", []))
    except OSError:
        return []


class Authorizer:
    def __init__(self, binding: Binding, agents: list[AgentDefinition] | None = None):
        self.binding = binding
        self.workspace = Path(os.path.realpath(binding.workspace))
        # Feature 005 overlay roles (afo-*) and their MCP servers exist only for a binding that binds one of them
        # (the afo-recovery-planner's single-node run); SWE work-order bindings see the base registry, unchanged
        afo = any(str(n.get("role", "")).startswith("afo-") for n in binding.nodes.values())
        onboarding = any(n.get("role") in ("onboard-model-author", "onboard-model-inspector")
                         for n in binding.nodes.values())
        self.agents = {a.id: a for a in (agents or load_agents(include_afo=afo, include_onboarding=onboarding)[0])}
        self.registry = load_registry(include_afo=afo)
        self.protected = list(ALWAYS_PROTECTED)
        # Supervisor protected paths (incl. workproducts/**, evidence/**) bind infrastructure-repair roles;
        # SWE authors legitimately produce new revisions of their own phase outputs (re-inspected on change).
        self.repair_protected = ALWAYS_PROTECTED + _protected_from_supervisor_policy()

    # -- path helpers -------------------------------------------------------------------
    def _rel(self, raw: str) -> str | None:
        if not isinstance(raw, str) or not raw or "\x00" in raw:
            return None
        p = Path(raw) if os.path.isabs(raw) else self.workspace / raw
        real = Path(os.path.realpath(p))
        try:
            return PurePosixPath(real.relative_to(self.workspace)).as_posix()
        except ValueError:
            return None

    @staticmethod
    def _paths(tool: str, tin: dict) -> list[str]:
        if tool == "apply_patch":
            return re.findall(r"^\*\*\* (?:Add|Update|Delete) File: (.+)$", str(tin.get("patch", "")), re.M) or [""]
        if tool == "read_many_files":
            return list(tin.get("paths") or [""])
        for k in ("file_path", "path"):
            if k in tin:
                return [tin[k]]
        return ["."] if tool in ("grep", "glob", "list_dir") else [""]

    # -- feature 008: brownfield work orders -----------------------------------------------
    def _manifest(self) -> dict:
        from ..brownfield import manifest_of

        return manifest_of(self.workspace)

    def _hidden_from(self, role_id: str, phase: str | None) -> list[str]:
        """Paths a requirement author (SWE.1 roles) may not read in a brownfield work order."""
        from ..brownfield import DELIVERY_DIR, delivered_paths

        if not (role_id == "swe1-author" or phase == "SWE.1"):
            return []
        m = self._manifest()
        paths = delivered_paths(m, None)
        return paths + [f"{DELIVERY_DIR}/**", "workproducts/SWE.3/delivered_code_facts.json",
                        "workproducts/SWE.3/code_trace_map*.json"] if paths else []

    def _delivered_write(self, role_id: str, rel: str) -> str | None:
        from ..brownfield import code_mode, delivered_paths

        m = self._manifest()
        code = delivered_paths(m)
        if not code:
            return None
        if rel not in code:  # no new driver source next to the delivered code (it would escape verification)
            return "BROWNFIELD_NEW_CODE_FILE" if rel.startswith(("software/ll/", "software/hal/", "software/src/",
                                                                   "software/include/")) else None
        if code_mode(m) != "FIX_ALLOWED":
            return "DELIVERED_CODE_FROZEN"
        if role_id != "swe3-author":
            return "DELIVERED_CODE_FIX_ROLE_ONLY"
        from ..brownfield.verify import _code_defects, _defect_files

        if not any(d.get("status") == "IN_FIX" and rel in _defect_files(d, code) for d in _code_defects(self.workspace)):
            return "DELIVERED_CODE_NO_DEFECT"
        return None

    # -- decision -----------------------------------------------------------------------
    def decide(self, node_id: str | None, tool: str, tool_input: dict | None) -> Decision:
        tin = tool_input if isinstance(tool_input, dict) else {}
        bound = self.binding.nodes.get(node_id or "")
        if not bound:
            return Decision(False, "UNBOUND_AGENT", f"node {node_id!r} has no bound role")
        role_id, phase = bound["role"], bound.get("phase")
        role = self.agents.get(role_id)
        if role is None:
            return Decision(False, "AGENT_SKILL_MISSING", role_id, role_id)
        if tool in DENY_NATIVE:
            return Decision(False, DENY_NATIVE[tool], tool, role_id)
        if tool in NO_SIDE_EFFECT:
            return Decision(True, "ALLOW_PLANNING", tool, role_id)
        if tool == "use_skill":
            name = tin.get("skill_name")
            return (Decision(True, "ALLOW_OWN_SKILL", name, role_id) if name == role_id
                    else Decision(False, "FOREIGN_SKILL_DENIED", str(name), role_id))
        if tool.startswith("mcp__"):
            op = op_from_fabro_tool(tool, self.registry)
            if op is None:
                return Decision(False, "MCP_TOOL_UNKNOWN", tool, role_id)
            if op not in role.allowed_tools or role_id not in self.registry.ops()[op].role_grants:
                return Decision(False, "MCP_TOOL_NOT_GRANTED", op, role_id, op)
            if role.phase and phase and role.phase != phase:
                return Decision(False, "PHASE_MISMATCH", f"{role.phase}!={phase}", role_id, op)
            return Decision(True, "ALLOW_MCP", op, role_id, op)
        if tool in READ_TOOLS:
            hidden = self._hidden_from(role_id, phase)
            for raw in self._paths(tool, tin):
                rel = self._rel(raw or ".")
                if rel is None:
                    return Decision(False, "PATH_OUTSIDE_WORKSPACE", str(raw)[:80], role_id)
                if _match(rel, SECRET_READ_DENY):
                    return Decision(False, "SECRET_PATH_DENIED", rel, role_id)
                if hidden and (_match(rel, hidden) or (tool in ("grep", "glob", "list_dir") and any(
                        (self.workspace / h).exists() and (rel in (".", "") or h.startswith(rel.rstrip("/") + "/"))
                        for h in hidden if "*" not in h))):
                    # feature 008 (FR-007): requirement authors never read the delivered code
                    return Decision(False, "DELIVERED_CODE_HIDDEN_FROM_REQUIREMENTS", rel, role_id)
                if role_id in ("fabric-repair", "mcp-integrator") and _match(rel, PRODUCT_PATHS):
                    return Decision(False, "PRODUCT_BASELINE_DENIED", rel, role_id)
            return Decision(True, "ALLOW_READ", tool, role_id)
        if tool in WRITE_TOOLS:
            if role.readonly:
                return Decision(False, "READONLY_ROLE_WRITE_DENIED", tool, role_id)
            for body in (str(tin.get("content") or tin.get("new_string") or ""), str(tin.get("old_string") or "")):
                if body.count("\\n") >= 3 and "\n" not in body:  # double-escaped JSON: one-line file / unmatched edit
                    return Decision(False, "ESCAPED_NEWLINES", "content has literal \\n sequences; resend with real "
                                    "line breaks, or rewrite the whole file with write_file", role_id)
            prefixes = ROLE_WRITE_PREFIXES.get(role_id, [])
            for raw in self._paths(tool, tin):
                rel = self._rel(raw)
                if rel is None or rel in ("", "."):
                    return Decision(False, "PATH_OUTSIDE_WORKSPACE", str(raw)[:80], role_id)
                protected = self.repair_protected if role_id in ("fabric-repair", "mcp-integrator") \
                    else self.protected
                if _match(rel, protected):
                    return Decision(False, "PROTECTED_PATH_DENIED", rel, role_id)
                denied = self._delivered_write(role_id, rel)
                if denied:  # feature 008 (FR-013/FR-014): delivered code is frozen or changes only for a CODE defect
                    return Decision(False, denied, rel, role_id)
                if not any(rel == p.rstrip("/") or rel.startswith(p) for p in prefixes):
                    return Decision(False, "WRITE_SCOPE_DENIED", rel, role_id)
            return Decision(True, "ALLOW_WRITE", tool, role_id)
        return Decision(False, "UNKNOWN_TOOL_DENIED", tool, role_id)
