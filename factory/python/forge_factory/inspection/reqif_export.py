"""Deterministic ReqIF 1.2 export of the SWE.1 EARS requirements (single source of truth: the markdown).

Generated by the SWE.1 author gate before the baseline is frozen, so `software_requirements.reqif` is part of the
SWE.1 baseline. Contents: one SPEC-OBJECT per SWR (ForeignID, Text, EARS pattern, source) and per verifying test
id, SPEC-RELATIONs "verified-by" from the trace CSV, and one SPECIFICATION hierarchy. Validated against the OMG
ReqIF XSD bundled with the Apache-2.0 `reqif` package and round-trip parsed by its parser. No model involvement.
"""
from __future__ import annotations

import csv
import hashlib
import io
import re
from pathlib import Path
from xml.sax.saxutils import quoteattr

from .ears import check_statement, extract

REQS = "workproducts/SWE.1/software_requirements.md"
TRACE = "traceability/requirements_to_tests.csv"
OUT = "workproducts/SWE.1/software_requirements.reqif"
FIXED_TIME = "2026-01-01T00:00:00Z"  # deterministic LAST-CHANGE (content hash identifies the revision)


def _id(*parts: str) -> str:
    return "_" + hashlib.sha256("|".join(parts).encode()).hexdigest()[:24]


def _sources(markdown: str) -> dict[str, str]:
    out, cur = {}, None
    for line in markdown.splitlines():
        m = re.match(r"^\s*(?:[-*]\s*)?\*\*(SWR-[A-Z0-9_.-]+)\*\*", line)
        if m:
            cur = m.group(1)
            continue
        s = re.match(r"^\s+-\s*Source:\s*(.+?)\s*$", line)
        if s and cur and cur not in out:
            out[cur] = s.group(1)
    return out


def build_xml(markdown: str, trace_csv: str, title: str) -> str:
    reqs = [check_statement(r) for r in extract(markdown)]
    src = _sources(markdown)
    rows = list(csv.DictReader(io.StringIO(trace_csv))) if trace_csv else []
    tests = sorted({(r.get("test_id") or "").strip() for r in rows if (r.get("test_id") or "").strip()})
    doc_hash = hashlib.sha256((markdown + trace_csv).encode()).hexdigest()
    a = quoteattr
    T = FIXED_TIME
    dt = _id("DT", "string")
    sot_r, sot_t, srt, st = _id("SOT", "swr"), _id("SOT", "test"), _id("SRT", "verified-by"), _id("ST", "swe1")
    ad = {k: _id("AD", k) for k in ("ForeignID", "Text", "EARS", "Source", "TestID")}

    def attr_def(key: str, name: str) -> str:
        return (f'<ATTRIBUTE-DEFINITION-STRING IDENTIFIER="{ad[key]}" LAST-CHANGE="{T}" LONG-NAME={a(name)}>'
                f'<TYPE><DATATYPE-DEFINITION-STRING-REF>{dt}</DATATYPE-DEFINITION-STRING-REF></TYPE>'
                f'</ATTRIBUTE-DEFINITION-STRING>')

    def val(key: str, v: str) -> str:
        return (f'<ATTRIBUTE-VALUE-STRING THE-VALUE={a(v)}><DEFINITION><ATTRIBUTE-DEFINITION-STRING-REF>{ad[key]}'
                f'</ATTRIBUTE-DEFINITION-STRING-REF></DEFINITION></ATTRIBUTE-VALUE-STRING>')

    req_ids = {r.req_id for r in reqs}

    def tid(t: str) -> str:
        # CAPA-021 (r85): a requirement verified by its Robot test is traced as test_id = the SWR id (CAPA-020); the
        # test object then had the requirement's xs:ID. Colliding test ids get their own namespace (others unchanged).
        return _id("ST", t) if t in req_ids else _id("SO", t)

    objs = [f'<SPEC-OBJECT IDENTIFIER="{_id("SO", r.req_id)}" LAST-CHANGE="{T}" LONG-NAME={a(r.req_id)}><VALUES>'
            f'{val("ForeignID", r.req_id)}{val("Text", r.text)}{val("EARS", r.pattern or "NONCONFORMANT")}'
            f'{val("Source", src.get(r.req_id, ""))}</VALUES><TYPE><SPEC-OBJECT-TYPE-REF>{sot_r}'
            f'</SPEC-OBJECT-TYPE-REF></TYPE></SPEC-OBJECT>' for r in reqs]
    objs += [f'<SPEC-OBJECT IDENTIFIER="{tid(t)}" LAST-CHANGE="{T}" LONG-NAME={a(t)}><VALUES>'
             f'{val("TestID", t)}</VALUES><TYPE><SPEC-OBJECT-TYPE-REF>{sot_t}</SPEC-OBJECT-TYPE-REF></TYPE>'
             f'</SPEC-OBJECT>' for t in tests]
    known = {r.req_id for r in reqs}
    rels = [f'<SPEC-RELATION IDENTIFIER="{_id("SR", r["requirement_id"].strip(), r["test_id"].strip())}" '
            f'LAST-CHANGE="{T}"><SOURCE><SPEC-OBJECT-REF>{_id("SO", r["requirement_id"].strip())}</SPEC-OBJECT-REF>'
            f'</SOURCE><TARGET><SPEC-OBJECT-REF>{tid(r["test_id"].strip())}</SPEC-OBJECT-REF></TARGET><TYPE>'
            f'<SPEC-RELATION-TYPE-REF>{srt}</SPEC-RELATION-TYPE-REF></TYPE></SPEC-RELATION>'
            for r in rows if r.get("requirement_id", "").strip() in known and (r.get("test_id") or "").strip()]
    hier = "".join(f'<SPEC-HIERARCHY IDENTIFIER="{_id("SH", r.req_id)}" LAST-CHANGE="{T}"><OBJECT><SPEC-OBJECT-REF>'
                   f'{_id("SO", r.req_id)}</SPEC-OBJECT-REF></OBJECT></SPEC-HIERARCHY>' for r in reqs)
    return (
        '<?xml version="1.0" encoding="UTF-8"?>\n'
        '<REQ-IF xmlns="http://www.omg.org/spec/ReqIF/20110401/reqif.xsd" '
        'xmlns:xhtml="http://www.w3.org/1999/xhtml">'
        f'<THE-HEADER><REQ-IF-HEADER IDENTIFIER="{_id("HDR", doc_hash)}"><COMMENT>Generated deterministically by '
        f'Forge-C from {REQS} (sha256 {doc_hash[:16]}); EARS markdown is the source of truth.</COMMENT>'
        f'<CREATION-TIME>{T}</CREATION-TIME><REQ-IF-TOOL-ID>Forge-C reqif_export 0.5</REQ-IF-TOOL-ID>'
        f'<REQ-IF-VERSION>1.0</REQ-IF-VERSION><SOURCE-TOOL-ID>Forge-C</SOURCE-TOOL-ID><TITLE>{_esc(title)}</TITLE>'
        '</REQ-IF-HEADER></THE-HEADER>'
        '<CORE-CONTENT><REQ-IF-CONTENT>'
        f'<DATATYPES><DATATYPE-DEFINITION-STRING IDENTIFIER="{dt}" LAST-CHANGE="{T}" LONG-NAME="String" '
        'MAX-LENGTH="4096"/></DATATYPES>'
        '<SPEC-TYPES>'
        f'<SPEC-OBJECT-TYPE IDENTIFIER="{sot_r}" LAST-CHANGE="{T}" LONG-NAME="Software Requirement"><SPEC-ATTRIBUTES>'
        f'{attr_def("ForeignID", "ReqIF.ForeignID")}{attr_def("Text", "ReqIF.Text")}'
        f'{attr_def("EARS", "EARS pattern")}{attr_def("Source", "Source")}</SPEC-ATTRIBUTES></SPEC-OBJECT-TYPE>'
        f'<SPEC-OBJECT-TYPE IDENTIFIER="{sot_t}" LAST-CHANGE="{T}" LONG-NAME="Verification Test"><SPEC-ATTRIBUTES>'
        f'{attr_def("TestID", "Test ID")}</SPEC-ATTRIBUTES></SPEC-OBJECT-TYPE>'
        f'<SPEC-RELATION-TYPE IDENTIFIER="{srt}" LAST-CHANGE="{T}" LONG-NAME="verified-by"/>'
        f'<SPECIFICATION-TYPE IDENTIFIER="{st}" LAST-CHANGE="{T}" LONG-NAME="SWE.1 Software Requirements"/>'
        '</SPEC-TYPES>'
        f'<SPEC-OBJECTS>{"".join(objs)}</SPEC-OBJECTS>'
        + (f'<SPEC-RELATIONS>{"".join(rels)}</SPEC-RELATIONS>' if rels else '')
        + f'<SPECIFICATIONS><SPECIFICATION IDENTIFIER="{_id("SPEC", "swe1")}" LAST-CHANGE="{T}" '
        f'LONG-NAME="SWE.1 Software Requirements"><TYPE><SPECIFICATION-TYPE-REF>{st}</SPECIFICATION-TYPE-REF></TYPE>'
        f'<CHILDREN>{hier}</CHILDREN></SPECIFICATION></SPECIFICATIONS>'
        '</REQ-IF-CONTENT></CORE-CONTENT></REQ-IF>\n')


def _esc(s: str) -> str:
    return s.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")


def validate(path: Path) -> dict:
    """XSD validation (bundled OMG ReqIF schema) + round-trip parse with the `reqif` package."""
    import reqif
    import xmlschema
    from reqif.parser import ReqIFParser

    xsd = Path(reqif.__file__).parent / "reqif_schema" / "reqif.xsd"
    issues = [f"XSD:{str(e)[:160]}" for e in list(xmlschema.XMLSchema(str(xsd)).iter_errors(str(path)))[:10]]
    n = 0
    try:
        bundle = ReqIFParser.parse(str(path))
        n = len(bundle.core_content.req_if_content.spec_objects or [])
    except Exception as exc:  # noqa: BLE001 - any parse failure is a finding
        issues.append(f"PARSE:{type(exc).__name__}:{str(exc)[:120]}")
    return {"verdict": "PASS" if not issues else "FAIL", "issues": issues, "spec_objects": n}


def export(ws: Path, title: str = "SWE.1 Software Requirements") -> dict:
    md = ws / REQS
    if not md.is_file():
        return {"verdict": "FAIL", "issues": ["NO_REQUIREMENTS_FILE"], "spec_objects": 0}
    tr = ws / TRACE
    out = ws / OUT
    out.write_text(build_xml(md.read_text(encoding="utf-8"), tr.read_text(encoding="utf-8") if tr.is_file() else "",
                             title), encoding="utf-8")
    return {**validate(out), "file": OUT}
