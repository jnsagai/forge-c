"""Isolated CODEX_HOME for factory Codex sessions: factory config only; the owner's personal Codex config, hooks,
plugins and MCP servers never load. Login: a separate `codex login` into this home (preferred), or - for probes -
a link to the owner's auth.json (token refresh may then rotate the shared refresh token)."""
from __future__ import annotations

import os
from pathlib import Path

from ..common import data_root

# Every Codex capability that can act outside the gate's MCP tools is turned off (codex 0.162.1 feature flags).
# code_mode_host stays ON: in this Codex version every tool call (MCP included) runs through code mode; its
# sandbox must not reach files, processes or the network directly (verified by the ACP probe tests).
CODEX = "toolchains/codex-0.162.1/bin/codex"  # pinned copy of the owner's standalone release (with code-mode host)
DISABLED_FEATURES = ("apps", "auth_elicitation", "browser_use", "browser_use_external", "browser_use_full_cdp_access",
                     "computer_use", "goals", "guardian_approval", "guardian_reuse_parent_compaction",
                     "hooks", "image_generation", "in_app_browser", "in_app_chat", "in_app_dictation",
                     "in_app_local_automation", "in_app_updates", "mentions_v2", "multi_agent", "multi_agent_v2",
                     "plugin_sharing", "plugins", "realtime_conversation", "remote_plugin", "shell_snapshot",
                     "shell_tool", "skill_mcp_dependency_install", "skill_search", "sleep_tool", "tool_suggest",
                     "tool_call_mcp_elicitation", "unified_exec", "unified_exec_tty", "view_image",
                     "workspace_dependencies", "worktrees", "write_stdin_approval", "memories", "browser_annotation_api",
                     "in_app_voice", "unified_exec_zsh_fork", "tool_search_always_defer_mcp_tools")
MODEL = "gpt-6.1-sol"
EFFORT = "high"


def home() -> Path:
    return data_root() / "codex-home"


# CAPA-045 / owner decision 2026-10-19: the final reply is only the requested JSON (prose costs tokens, blurs answers)
VERBOSITY = "low"


def config_text(model: str = MODEL, effort: str = EFFORT) -> str:
    lines = ["# GENERATED by forge_factory.acp.codex_home - factory Codex profile (do not edit)",
             f'model = "{model}"', f'model_reasoning_effort = "{effort}"', f'model_verbosity = "{VERBOSITY}"',
             'approval_policy = "on-request"',
             'sandbox_mode = "read-only"', 'web_search = "disabled"', "", "[history]", 'persistence = "none"', "",
             "[features]"] + [f"{f} = false" for f in DISABLED_FEATURES]
    return "\n".join(lines) + "\n"


def ensure(link_owner_auth: bool = False, model: str = MODEL, effort: str = EFFORT) -> Path:
    h = home()
    h.mkdir(parents=True, exist_ok=True)
    os.chmod(h, 0o700)
    (h / "config.toml").write_text(config_text(model, effort))
    auth = h / "auth.json"
    if link_owner_auth and not auth.exists():
        auth.symlink_to(Path.home() / ".codex" / "auth.json")
    return h


def logged_in() -> bool:
    return (home() / "auth.json").exists()
