"""CAPA-054 (h002): the swe4-author skill listed verification/unit/unit_verification_summary.json as an output, but the
policy (rightly) denies authors any write under verification/ - that file is evidence the packager generates from the
tool results. The author tried, was refused and escalated DEF-001 (FACTORY); the package stayed BLOCKED on it."""
import yaml
from forge_factory.common import REPO_ROOT
from forge_factory.policy.authz import ROLE_WRITE_PREFIXES
from forge_factory.registry import skillgen


def _authors():
    roles = yaml.safe_load((REPO_ROOT / "config/factory/agents.yaml").read_text())["agents"]
    return [r for r in roles if r.get("phase") and r["id"].endswith("-author")]


def test_capa054_every_author_skill_output_is_writable_by_the_role():
    bad = {r["id"]: [o for o in skillgen._outputs(r)
                     if not any(o.startswith(p) for p in ROLE_WRITE_PREFIXES.get(r["id"], []))]
           for r in _authors()}
    assert {k: v for k, v in bad.items() if v} == {}


def test_capa054_rendered_skills_name_no_verification_output():
    for r in _authors():
        text = (REPO_ROOT / f".fabro/skills/{r['id']}/SKILL.md").read_text()
        outputs = text.split("## Outputs", 1)[1].split("\n## ", 1)[0]
        assert "- `verification/" not in outputs, r["id"]
        if r["phase"] >= "SWE.4":
            assert "generated by the factory packager" in outputs, r["id"]
