"""CAPA-212 (SPI LL L41O, 2026-11-10 04:03Z, third set inspection): SQ-07 "interdependency and feasibility analysis"
found no feasibility assessment of the budget requirements SWR-041..SWR-045. Those rows are generated by the factory
from the work-order budgets (no author task owns them; the finding could only fall back to the cross-cutting task).
The assembler now writes a factual "Budget feasibility" section: each budget with its SWR id and source, the
implementation form quoted from the work-order scope, the computed relationship of the simulation budgets, what is
assessed at SWE.1 and what only the SWE.6 measurement confirms, and the residual risk. No claim beyond those facts."""
from __future__ import annotations

import re

from test_lrtx_swe1 import ANSWERS, _gate, _scripted, ws  # noqa: F401 - the IWDG LL workspace fixture

from forge_factory.lrtx import structured as S
from forge_factory.lrtx import swe1


def _md(ws, monkeypatch):  # noqa: F811
    monkeypatch.setattr(S, "call", _scripted(ANSWERS, []))
    assert swe1.visit(ws, "qwen3-coder:30b")["status"] == "PASS"
    return (ws / swe1.REQS).read_text()


def _section(md):
    return md.split("## Budget feasibility", 1)[1].split("\n## ", 1)[0]


def test_each_budget_requirement_is_assessed_in_the_feasibility_section(ws, monkeypatch):  # noqa: F811
    md = _md(ws, monkeypatch)
    sec = _section(md)
    budget_ids = re.findall(r"\*\*(SWR-\d{3})\*\* The IWDG LL driver shall (?:occupy|use) at most", md)
    assert budget_ids and all(i in sec for i in budget_ids)
    assert "SWE.6" in sec and "Residual risk" in sec and "not yet measured" in sec
    assert md.index("## Resource and timing budget requirements") < md.index("## Budget feasibility") < md.index(
        "## Open points")


def test_the_section_quotes_the_scope_and_claims_nothing_else(ws, monkeypatch):  # noqa: F811
    md = _md(ws, monkeypatch)
    sec = _section(md)
    m = swe1._manifest(ws)
    assert "Implementation form (work-order scope): " + m["scope"][0].strip() in sec
    for word in ("guaranteed", "proven", "certified"):
        assert word not in sec.lower()


def test_without_a_simulation_budget_no_cpu_feasibility_is_claimed(ws, monkeypatch):  # noqa: F811
    sec = _section(_md(ws, monkeypatch))  # the IWDG LL example declares no simulation performance budget
    assert "allocates no simulation performance budget" in sec and "binding" not in sec


def test_the_simulation_budgets_relationship_is_computed(ws, monkeypatch):  # noqa: F811
    import forge_factory.simulation_performance as SP

    monkeypatch.setattr(SP, "selected", lambda _ws: {"instructions_per_call": 64, "microseconds_per_call": 100,
                                                     "performance_mips": 100})
    rows = [{"key": k, "swr": f"SWR-{n:03d}"} for n, k in enumerate(
        ["budget_flash", "budget_static_ram", "budget_stack", "budget_simulation_cpu", "budget_simulation_time"], 41)]
    sec = "\n".join(swe1.budget_feasibility(ws, swe1._manifest(ws), rows))
    assert "SWR-044 (64 executed instructions per call) and SWR-045 (100 microseconds" in sec
    assert "i.e. 10000 instructions" in sec and "the instruction budget is the binding one" in sec


def test_the_unchanged_gate_still_freezes(ws, monkeypatch):  # noqa: F811
    _md(ws, monkeypatch)
    assert _gate(ws, monkeypatch) == 0
